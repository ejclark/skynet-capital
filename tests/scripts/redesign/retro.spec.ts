import { describe, expect, it } from "@rstest/core";
import { parseReadback, retroMarkdown, retroOf } from "../../../scripts/redesign/retro.mjs";

// docs/process/REDESIGN.md → step i: a retro starts from the facts the read-backs already posted —
// each round's question, his picks and his notes word for word — and the ledger's numbers. The
// shapes below are the read-back comments steer:readback writes (#5160 has seventeen of them).

const readback = (round: number, at: string, rest: string) => ({
  at,
  body: `**Answered on the decisions page, design-5160-r${round}.**\n\n${rest}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_`,
});

const r0 = readback(
  0,
  "2026-10-11T17:18:00Z",
  [
    "**Q1 · Which problem should the next round fix first?**",
    '- Fix first: problem A, "Nine blocks of text"',
    '- Look closer: A ("Nine blocks of text"), B ("The desktop row")',
    "",
    "Eric's note:",
    "",
    "> We need to outline if we are looking at our ledger or transaction logs.",
  ].join("\n"),
);
const r8 = readback(
  8,
  "2026-10-12T02:45:00Z",
  [
    "**Q1 · How is the neutral OTM zone drawn?**",
    '- Build: option thin, "A thin line"',
    '- More of: grey ("Solid grey")',
    "- Not: hollow",
    "",
    "Per pin:",
    "- Option thin · pin 1 (A thin line) — 👍 keep — “love the green.",
    "  What are the extra lines above the bar?”",
    "- Option grey · pin 1 (Solid grey) — no signal",
  ].join("\n"),
);
const other = { at: "2026-10-12T17:48:00Z", body: "**Eric, 2026-10-12 (chat):** rename it." };

describe("a read-back comment becomes one round of facts", () => {
  it("reads the round, the question, the picks and his notes word for word", () => {
    expect(parseReadback(r8)).toEqual({
      issue: 5160,
      round: 8,
      at: "2026-10-12T02:45:00Z",
      question: "How is the neutral OTM zone drawn?",
      picks: [
        { kind: "Build", what: 'option thin, "A thin line"' },
        { kind: "More of", what: 'grey ("Solid grey")' },
        { kind: "Not", what: "hollow" },
      ],
      notes: [
        {
          on: "Option thin · pin 1 (A thin line)",
          reaction: "👍 keep",
          text: "love the green.\nWhat are the extra lines above the bar?",
        },
      ],
    });
  });

  it("takes a quoted note as a note on the round, and skips a comment that isn't a read-back", () => {
    expect(parseReadback(r0)?.notes).toEqual([
      {
        on: "the round",
        reaction: null,
        text: "We need to outline if we are looking at our ledger or transaction logs.",
      },
    ]);
    expect(parseReadback(other)).toBeNull();
  });
});

describe("the retro's facts across a screen's rounds", () => {
  it("orders the rounds and counts what the ledger needs", () => {
    const facts = retroOf([r8, other, r0]);
    expect(facts.rounds.map((r) => r.round)).toEqual([0, 8]);
    expect(facts.ledger).toEqual({
      rounds: 2,
      firstBuild: 8,
      builds: [8],
      notesAfterRound0: 1,
      from: "2026-10-11T17:18:00Z",
      to: "2026-10-12T02:45:00Z",
    });
  });

  it("prints a timeline a session can judge from", () => {
    const md = retroMarkdown(5160, retroOf([r0, r8]));
    expect(md).toContain("## r8 · 2026-10-12 02:45 · How is the neutral OTM zone drawn?");
    expect(md).toContain("- Build: option thin");
    expect(md).toContain("- First Build pick: r8");
    expect(md).toContain("- Notes after round 0: 1");
  });
});
