import { execFileSync } from "node:child_process";
import { describe, expect, it } from "@rstest/core";
import { audit } from "../../../scripts/moneypenny/audit.mjs";
import {
  CLOCK_ISSUE_TITLE,
  CLOCK_RUNS_PATH,
  CLOCK_STALE_HOURS,
  clockIntents,
  clockOrUnknown,
  closeClockIssue,
  openClockIssue,
  readClock,
} from "../../../scripts/moneypenny/clock-watch.mjs";

// THE CLOCK HAS A WATCHER (#6470: clock-has-no-watcher, nothing-watches-the-clock). The 15-minute
// bots catch-up is the only schedule in the repo, and since #6476 it also starts a stopped bots
// machine and runs the fitness contracts — so a clock that stops silences every one of them, and
// before this nothing read whether it was ticking. The push-tick audit now reads the newest
// SUCCESSFUL scheduled run (a run that started and failed is not a tick), keeps one `[fitness]`
// issue while it is older than 3h, and closes it when the clock is back. Said plainly: this is
// noticed at the next merge to main, not within 3 hours.

const NOW = Date.parse("2026-11-01T12:00:00Z");
const at = (hoursAgo: number) => new Date(NOW - hoursAgo * 3_600_000).toISOString();
const open = { number: 6600, title: CLOCK_ISSUE_TITLE };

describe("clockIntents — keep one issue while the clock is stale, close it when it is back", () => {
  it("does nothing while the newest successful scheduled run is fresh and no issue is open", () => {
    expect(clockIntents({ hoursSince: 0.4, newestSuccessAt: at(0.4), openIssue: null })).toEqual(
      [],
    );
  });

  it(`opens the issue once the newest successful scheduled run is over ${CLOCK_STALE_HOURS}h old`, () => {
    const [i] = clockIntents({ hoursSince: 3.5, newestSuccessAt: at(3.5), openIssue: null });
    expect(i?.kind).toBe("open-clock-issue");
    expect(i?.title).toBe(CLOCK_ISSUE_TITLE);
    expect(i?.body).toContain("3.5h");
    expect(i?.body).toContain("next merge");
    expect(i?.body).toContain("_Generated by [Claude Code](https://claude.ai/code)_");
  });

  it("keeps ONE issue — a stale clock with its issue already open adds nothing on the next push", () => {
    expect(clockIntents({ hoursSince: 9, newestSuccessAt: at(9), openIssue: open })).toEqual([]);
  });

  it("closes the issue when a successful scheduled run is fresh again", () => {
    const [i] = clockIntents({ hoursSince: 0.2, newestSuccessAt: at(0.2), openIssue: open });
    expect(i?.kind).toBe("close-clock-issue");
    expect(i?.issueNumber).toBe(6600);
    expect(i?.body).toContain("back");
  });

  it("treats no successful scheduled run at all as stale — a clock that never ticked is stopped", () => {
    const [i] = clockIntents({ hoursSince: null, newestSuccessAt: null, openIssue: null });
    expect(i?.kind).toBe("open-clock-issue");
    expect(i?.body).toContain("no successful scheduled run");
  });

  it("does not fire at the threshold's edge below it", () => {
    expect(
      clockIntents({
        hoursSince: CLOCK_STALE_HOURS - 0.1,
        newestSuccessAt: at(2.9),
        openIssue: null,
      }),
    ).toEqual([]);
  });
});

describe("readClock — one REST call per tick, the newest successful scheduled run", () => {
  const issues = [{ number: 1, title: "something else" }, open];

  it("asks for the newest successful run of the schedule event only, and finds the open issue by title", () => {
    const calls: string[] = [];
    const rest = (path: string) => {
      calls.push(path);
      return { total_count: 1769, workflow_runs: [{ created_at: at(1.5), event: "schedule" }] };
    };
    const c = readClock(NOW, issues, { rest });
    expect(calls).toEqual([CLOCK_RUNS_PATH]);
    expect(c.hoursSince).toBeCloseTo(1.5, 5);
    expect(c.newestSuccessAt).toBe(at(1.5));
    expect(c.openIssue).toEqual(open);
  });

  it("reads a body without the runs list as unknown (throws), never as a stopped clock", () => {
    expect(() => readClock(NOW, [], { rest: () => null })).toThrow("did not return a runs list");
    expect(() => readClock(NOW, [], { rest: () => ({ message: "oops" }) })).toThrow();
    const warned: string[] = [];
    expect(clockOrUnknown(NOW, [], { rest: () => null, log: (m) => warned.push(m) })).toBeNull();
    expect(warned).toHaveLength(1);
  });

  it("reads an empty list as no successful scheduled run, not as fresh", () => {
    const c = readClock(NOW, [], { rest: () => ({ total_count: 0, workflow_runs: [] }) });
    expect(c.hoursSince).toBeNull();
    expect(c.openIssue).toBeNull();
  });

  // Soft on failure, like the stranded-PR re-arm: the stall, silent-feedback and conflict checks
  // ride the same run, and one unreadable Actions list must not take their eyes with it.
  it("clockOrUnknown reads a failed REST call as unknown (null), said out loud, never as stale", () => {
    const warned: string[] = [];
    const log = (m: string) => warned.push(m);
    const c = clockOrUnknown(NOW, issues, {
      rest: () => {
        throw new Error("returned error: 503");
      },
      log,
    });
    expect(c).toBeNull();
    expect(warned.join("\n")).toContain("clock watch skipped");
    expect(audit({ clock: c })).toEqual([]);
  });
});

describe("the audit carries the clock's intents", () => {
  it("audit() emits the open intent from deps.clock", () => {
    const intents = audit({ clock: { hoursSince: 4, newestSuccessAt: at(4), openIssue: null } });
    expect(intents.map((i) => i.kind)).toEqual(["open-clock-issue"]);
  });

  it("audit() emits nothing when deps.clock is absent — a fixture without it is unchanged", () => {
    expect(audit({})).toEqual([]);
  });

  // The router's dry run, over a fixture that carries `deps.clock`: the same path the push tick
  // takes (`--audit` → `audit(fixtureDeps)` → execute), minus the writes.
  it("the push tick's dry run prints the open intent for a stopped clock", () => {
    const out = execFileSync(
      "node",
      [
        "scripts/moneypenny/index.mjs",
        "--dry-run",
        "--event",
        "tests/fixtures/events/audit-clock-stopped.json",
      ],
      { cwd: process.cwd(), encoding: "utf8" },
    );
    const intents = JSON.parse(out) as { kind: string; title?: string }[];
    expect(intents).toHaveLength(1);
    expect(intents[0]).toMatchObject({ kind: "open-clock-issue", title: CLOCK_ISSUE_TITLE });
  });
});

describe("the acts — the two gh writes, recorded", () => {
  const recorder = () => {
    const calls: string[][] = [];
    const run = (cmd: string, args: string[]) => {
      calls.push([cmd, ...args]);
      return "https://github.com/ejclark/skynet-capital/issues/6600";
    };
    return { calls, run };
  };

  it("openClockIssue creates one bug issue assigned to the owner, like the other [fitness] issues", () => {
    const { calls, run } = recorder();
    const [i] = clockIntents({ hoursSince: 3.5, newestSuccessAt: at(3.5), openIssue: null });
    if (!i) throw new Error("expected an open intent");
    const line = openClockIssue(i, { run });
    expect(calls).toHaveLength(1);
    expect(calls[0]?.slice(0, 3)).toEqual(["gh", "issue", "create"]);
    expect(calls[0]).toContain("--label");
    expect(calls[0]).toContain("bug");
    expect(calls[0]).toContain("--assignee");
    expect(calls[0]).toContain("ejclark");
    expect(calls[0]).toContain(CLOCK_ISSUE_TITLE);
    expect(line).toContain("6600");
  });

  it("closeClockIssue closes it with the reason in one call", () => {
    const { calls, run } = recorder();
    const [i] = clockIntents({ hoursSince: 0.2, newestSuccessAt: at(0.2), openIssue: open });
    if (!i) throw new Error("expected a close intent");
    closeClockIssue(i, { run });
    expect(calls).toHaveLength(1);
    expect(calls[0]?.slice(0, 4)).toEqual(["gh", "issue", "close", "6600"]);
    expect(calls[0]).toContain("--comment");
  });
});
