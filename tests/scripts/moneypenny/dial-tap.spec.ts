import { readFileSync } from "node:fs";
import {
  type DialComment,
  executeDialTap,
  executeDialTidy,
  type LabelEvent,
  planDialTap,
  routeDial,
} from "../../../scripts/moneypenny/dial-tap.mjs";
import { route } from "../../../scripts/moneypenny/index.mjs";
import { FOOTER } from "../../../scripts/moneypenny/labels.mjs";
import {
  loadWorkModeConfig,
  resolveWorkMode,
  type WorkModeConfig,
} from "../../../scripts/moneypenny/work-mode.mjs";

// ONE TAP ON THE DIAL (#6470). A tap leaves exactly one label and a footed end time. The two things
// that must never happen: a surge reading past the weekly reset, and a label from anyone but him
// switching a surge on, which is why a bot's surge label writes nothing at all.

const config: WorkModeConfig = loadWorkModeConfig();
const RESET = "2026-11-03T05:00:00Z";
const TAP = "2026-11-02T10:00:00Z";
const ERIC = "ejclark";

const tap = (position: string, actor = ERIC, app: string | null = null, at = TAP): LabelEvent => ({
  label: `work-mode:${position}`,
  createdAt: at,
  actor,
  app,
});

const plan = (
  position: string,
  event: LabelEvent,
  labels = [`work-mode:${position}`, "work-mode:normal"],
  comments: DialComment[] = [],
) =>
  planDialTap({
    label: `work-mode:${position}`,
    labels,
    events: [event],
    comments,
    config,
  });

/** What the lanes read after a tap's writes land, by the reader they really use. */
const readAfter = (
  position: string,
  event: LabelEvent,
  comment: string | null,
  now: string,
  extra: DialComment[] = [],
) =>
  resolveWorkMode({
    labels: [`work-mode:${position}`],
    events: [event],
    comments: [
      ...extra,
      ...(comment
        ? [
            {
              body: comment,
              createdAt: "2026-11-02T10:00:20Z",
              author_association: "NONE",
              user: { type: "Bot" },
            },
          ]
        : []),
    ],
    now: Date.parse(now),
    config,
  });

describe("what a tap writes", () => {
  it("clears the other dial labels, so exactly one remains", () => {
    const out = plan("conserve", tap("conserve"), [
      "work-mode:conserve",
      "work-mode:normal",
      "work-mode:surge",
      "other-label",
    ]);
    expect(out.remove.toSorted()).toEqual(["work-mode:normal", "work-mode:surge"]);
  });

  it("writes conserve a footed end time at the next reset, whoever tapped", () => {
    const out = plan("conserve", tap("conserve", "skynet-envoy[bot]"));
    expect(out.comment).toContain(`conserve until ${RESET}`);
    expect(out.comment).toContain("Generated by [Claude Code]");
  });

  it("makes a conserve tap read conserve until the reset, and normal after it", () => {
    const { comment } = plan("conserve", tap("conserve", "skynet-envoy[bot]"));
    const during = readAfter("conserve", tap("conserve"), comment, "2026-11-03T04:59:00Z");
    expect(during.position).toBe("conserve");
    expect(during.until).toBe(RESET);
    const after = readAfter("conserve", tap("conserve"), comment, "2026-11-03T05:00:00Z");
    expect(after.position).toBe("normal");
  });

  it("writes halt no end date, because a brake never releases itself", () => {
    const out = plan("halt", tap("halt", "skynet-envoy[bot]"));
    expect(out.comment).toBeNull();
    expect(out.remove).toEqual(["work-mode:normal"]);
    expect(readAfter("halt", tap("halt"), out.comment, "2026-12-25T00:00:00Z").position).toBe(
      "halt",
    );
  });

  it("writes normal nothing to end, and still clears the other label", () => {
    const out = plan("normal", tap("normal"), ["work-mode:normal", "work-mode:surge"]);
    expect(out.comment).toBeNull();
    expect(out.remove).toEqual(["work-mode:surge"]);
  });

  it("leaves a setting's own end date alone, so a session's reading is not overwritten", () => {
    const own = {
      body: "surge until 2026-11-02T20:00:00Z",
      createdAt: "2026-11-02T10:00:01Z",
      author_association: "OWNER",
    };
    const out = plan("surge", tap("surge"), ["work-mode:surge"], [own]);
    expect(out.comment).toBeNull();
    expect(readAfter("surge", tap("surge"), null, "2026-11-02T21:00:00Z", [own]).position).toBe(
      "normal",
    );
  });

  it("does not take an old end date for this setting's own", () => {
    const old = {
      body: "conserve until 2026-11-30",
      createdAt: "2026-10-01T00:00:00Z",
      author_association: "OWNER",
    };
    expect(plan("conserve", tap("conserve"), undefined, [old]).comment).toContain(RESET);
  });
});

describe("surge is his alone", () => {
  it("writes his own surge an end time at the reset, and it goes live", () => {
    const { comment } = plan("surge", tap("surge"));
    expect(comment).toContain(`surge until ${RESET}`);
    const live = readAfter("surge", tap("surge"), comment, "2026-11-02T12:00:00Z");
    expect(live.position).toBe("surge");
  });

  it("never reads his surge past the reset, one minute after it", () => {
    const { comment } = plan("surge", tap("surge"));
    expect(readAfter("surge", tap("surge"), comment, "2026-11-03T05:01:00Z").position).toBe(
      "normal",
    );
  });

  it.each([
    ["a bot", tap("surge", "skynet-envoy[bot]")],
    ["another person", tap("surge", "someone-else")],
    ["a session on his login through an app", tap("surge", ERIC, "claude")],
  ])("writes nothing at all for a surge label from %s", (_who, event) => {
    const out = plan("surge", event);
    expect(out).toEqual({ remove: [], comment: null, why: expect.stringContaining("surge by") });
  });

  it("keeps a bot's surge label reading normal with the warning, because nothing was written", () => {
    const event = tap("surge", "skynet-envoy[bot]");
    const read = readAfter("surge", event, plan("surge", event).comment, "2026-11-02T12:00:00Z");
    expect(read.position).toBe("normal");
    expect(read.warning).toMatch(/no "until/);
  });

  it("reads a login in any case as his, as GitHub does", () => {
    expect(plan("surge", tap("surge", "EJClark")).comment).toContain(RESET);
  });
});

describe("a tap a newer tap overtook", () => {
  it("does nothing, so two runs cannot each clear the other's label", () => {
    const events = [
      tap("conserve", ERIC, null, "2026-11-02T10:00:00Z"),
      tap("halt", ERIC, null, "2026-11-02T10:00:05Z"),
    ];
    const older = planDialTap({
      label: "work-mode:conserve",
      labels: ["work-mode:conserve", "work-mode:halt"],
      events,
      config,
    });
    expect(older.remove).toEqual([]);
    expect(older.comment).toBeNull();
    const newer = planDialTap({
      label: "work-mode:halt",
      labels: ["work-mode:conserve", "work-mode:halt"],
      events,
      config,
    });
    expect(newer.remove).toEqual(["work-mode:conserve"]);
  });

  it("writes nothing when GitHub has not listed the label event yet", () => {
    const out = planDialTap({
      label: "work-mode:surge",
      labels: ["work-mode:surge", "work-mode:normal"],
      events: [],
      config,
    });
    expect(out.remove).toEqual([]);
    expect(out.comment).toBeNull();
  });

  it("ignores a work-mode label that is not a position", () => {
    const out = planDialTap({
      label: "work-mode:sideways",
      labels: ["work-mode:sideways", "work-mode:normal"],
      events: [tap("sideways")],
      config,
    });
    expect(out.remove).toEqual([]);
  });
});

describe("the wiring", () => {
  const labeled = (name: string, number = 4153) => ({
    eventName: "issues",
    action: "labeled",
    payload: { label: { name }, issue: { number } },
  });

  it("reaches route(), and only on a dial label going on", () => {
    expect(route(labeled("work-mode:conserve"))).toEqual([
      { kind: "route-dial", issueNumber: 4153, label: "work-mode:conserve" },
    ]);
    expect(route(labeled("feedback"))).toEqual([]);
    expect(routeDial({ ...labeled("work-mode:conserve"), action: "unlabeled" })).toEqual([]);
  });

  /** A fake gh: answers the three reads, records every write. */
  const fakeGh = (events: LabelEvent[], labels: string[]) => {
    const writes: string[][] = [];
    const exec = (_cmd: string, args: readonly string[]) => {
      if (args.includes("-X")) {
        writes.push([...args]);
        return "";
      }
      const path = args.find((a) => a.startsWith("repos/")) ?? "";
      if (path.includes("/events"))
        return events
          .map((e) =>
            JSON.stringify({
              label: e.label,
              createdAt: e.createdAt,
              actor: e.actor,
              app: e.app ?? null,
            }),
          )
          .join("\n");
      if (path.includes("/comments")) return "";
      return JSON.stringify({ labels });
    };
    return { exec, writes };
  };
  const intent = (position: string, issueNumber = 4153) => ({
    kind: "route-dial" as const,
    issueNumber,
    label: `work-mode:${position}`,
  });

  it("carries one tap through to one label removal and one footed comment", () => {
    const { exec, writes } = fakeGh([tap("conserve")], ["work-mode:conserve", "work-mode:normal"]);
    executeDialTap(intent("conserve"), { exec, config });
    expect(writes[0]).toEqual([
      "api",
      "-X",
      "DELETE",
      "repos/{owner}/{repo}/issues/4153/labels/work-mode%3Anormal",
    ]);
    expect(writes[1]?.at(-1)).toContain(`body=conserve until ${RESET}`);
    expect(writes).toHaveLength(2);
  });

  it("makes no write at all for a bot's surge label", () => {
    const { exec, writes } = fakeGh(
      [tap("surge", "skynet-envoy[bot]")],
      ["work-mode:surge", "work-mode:normal"],
    );
    executeDialTap(intent("surge"), { exec, config });
    expect(writes).toEqual([]);
  });

  it("makes no read or write for a work-mode label on another issue", () => {
    const calls: unknown[] = [];
    const exec = (...args: unknown[]) => {
      calls.push(args);
      return "";
    };
    executeDialTap(intent("conserve", 99), { exec, config });
    expect(calls).toEqual([]);
  });
});

// The push tick's half. The audit decided on a read a moment old, and in that moment someone may have
// tapped a brake on, so the write reads again and every case below that must not write goes through
// the same reader the lanes use.
describe("executeDialTidy", () => {
  const SET = "2026-10-27T10:00:00Z";
  const WRITTEN = "2026-10-27T10:00:20Z";
  const AFTER = Date.parse("2026-11-03T06:00:00Z");
  const endDate = (text: string) => ({
    body: text,
    createdAt: WRITTEN,
    author_association: "OWNER",
    user: { type: "User" },
  });
  const intent = (position: string) => ({
    kind: "tidy-ended-dial" as const,
    issueNumber: 4153,
    label: `work-mode:${position}`,
    reason: "read a moment ago",
  });

  /** A fake `gh` over the issue as it is now. The writes change `labels`, so a second pass sees them. */
  const fakeGh = (start: string[], comments: DialComment[], events: LabelEvent[]) => {
    const labels = [...start];
    const writes: string[][] = [];
    const exec = (_cmd: string, args: readonly string[]) => {
      const path = args.find((a) => a.startsWith("repos/")) ?? "";
      if (args.includes("-X")) {
        writes.push([...args]);
        if (args.includes("DELETE"))
          labels.splice(labels.indexOf(decodeURIComponent(path.split("/").at(-1) ?? "")), 1);
        else if (path.endsWith("/labels")) labels.push("work-mode:normal");
        return "";
      }
      if (path.includes("/events")) return events.map((e) => JSON.stringify(e)).join("\n");
      if (path.includes("/comments")) return comments.map((c) => JSON.stringify(c)).join("\n");
      return JSON.stringify({
        title: "Work mode: SURGE",
        labels: labels.map((name) => ({ name })),
      });
    };
    return { exec, writes, labels };
  };
  const set = (position: string) => [{ label: `work-mode:${position}`, createdAt: SET }];

  it("puts normal on, takes the ended label off, and leaves one footed comment", () => {
    const { exec, writes, labels } = fakeGh(
      ["work-mode:surge"],
      [endDate(`surge until ${RESET}`)],
      set("surge"),
    );
    executeDialTidy(intent("surge"), { exec, config, now: AFTER });
    expect(writes.map((w) => w.slice(2, 4))).toEqual([
      ["POST", "repos/{owner}/{repo}/issues/4153/labels"],
      ["DELETE", "repos/{owner}/{repo}/issues/4153/labels/work-mode%3Asurge"],
      ["POST", "repos/{owner}/{repo}/issues/4153/comments"],
    ]);
    expect(writes[0]).toContain("labels[]=work-mode:normal");
    expect(labels).toEqual(["work-mode:normal"]);
    const comment = writes[2]?.at(-1) ?? "";
    expect(comment).toContain(FOOTER);
    expect(comment).toContain("surge expired at");
    // The reader takes any "until <date>" as an end date, and a later tap could read this one.
    expect(comment).not.toMatch(/until/i);
  });

  it("does it once: a second pass reads normal and writes nothing", () => {
    const { exec, writes } = fakeGh(
      ["work-mode:surge"],
      [endDate(`surge until ${RESET}`)],
      set("surge"),
    );
    executeDialTidy(intent("surge"), { exec, config, now: AFTER });
    executeDialTidy(intent("surge"), { exec, config, now: AFTER });
    expect(writes).toHaveLength(3);
  });

  it.each([
    // A brake with no end date, the state this must never release.
    ["a halt with no end date", ["work-mode:halt"], [], set("halt"), "halt"],
    // Tapped on after the audit read an ended surge. Releasing this one is the race the re-read closes.
    ["a brake tapped on since the audit read", ["work-mode:halt"], [], set("halt"), "surge"],
    [
      "an end date still ahead",
      ["work-mode:conserve"],
      [endDate("conserve until 2026-11-04T05:00Z")],
      set("conserve"),
      "conserve",
    ],
    ["a surge with no end date", ["work-mode:surge"], [], set("surge"), "surge"],
    ["two labels on the dial", ["work-mode:surge", "work-mode:normal"], [], [], "surge"],
    ["a dial already at normal", ["work-mode:normal"], [], [], "surge"],
  ] as [string, string[], DialComment[], LabelEvent[], string][])(
    "writes nothing for %s",
    (_what, start, comments, events, position) => {
      const { exec, writes, labels } = fakeGh(start, comments, events);
      executeDialTidy(intent(position), { exec, config, now: AFTER });
      expect(writes).toEqual([]);
      expect(labels).toEqual(start);
    },
  );

  it("touches nothing for an intent naming another issue", () => {
    const { exec, writes, labels } = fakeGh(
      ["work-mode:surge"],
      [endDate(`surge until ${RESET}`)],
      set("surge"),
    );
    executeDialTidy({ ...intent("surge"), issueNumber: 99 }, { exec, config, now: AFTER });
    expect(writes).toEqual([]);
    expect(labels).toEqual(["work-mode:surge"]);
  });

  it("is what the push tick's intent runs", () => {
    const source = readFileSync("scripts/moneypenny/index.mjs", "utf8");
    expect(source).toContain(`"tidy-ended-dial": (i) => executeDialTidy(i)`);
  });
});
