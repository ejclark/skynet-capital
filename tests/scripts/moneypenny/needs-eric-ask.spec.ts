describe("the lane's ask is written once, above the fold", () => {
  const FOLDED = "**Ask.**\n\n<details><summary>x</summary>\n\nbrief\n</details>\n";

  it("lands above the fold, where the rule and the digest both read it", () => {
    const body = withLaneAsk(FOLDED, "Pick A or B? — why");
    expect(stated(body)).toBe(true);
    expect(body.indexOf("Needs from you")).toBeLessThan(body.indexOf("<details"));
    expect(body.startsWith("**Ask.**")).toBe(true);
  });

  it("sits above the attribution footer on a body with no fold", () => {
    const body = withLaneAsk(SESSION_BODY, "Pick A or B?");
    expect(body.indexOf("Needs from you")).toBeLessThan(body.indexOf("Generated by"));
  });

  it("replaces its own earlier ask, so a second stop does not stack a second callout", () => {
    const once = withLaneAsk(FOLDED, "First ask?");
    const twice = withLaneAsk(once, "Second ask?");
    expect(twice).toContain("Second ask?");
    expect(twice).not.toContain("First ask?");
    expect(twice.match(/Needs from you/g)).toHaveLength(1);
  });

  it("leaves a callout someone else wrote alone: the decision stays in one place", () => {
    const written = "**Ask.**\n\n> [!IMPORTANT]\n> **Needs from you**\n> 1. Theirs?\n";
    expect(withLaneAsk(written, "Mine?")).toBe(written);
  });

  it("holds one line within the callout's length limit", () => {
    const body = withLaneAsk("", `line one\nline two ${"x".repeat(300)}`);
    const item = /^> 1\. (.+)$/m.exec(body)?.[1] ?? "";
    expect(item.startsWith("line one line two")).toBe(true);
    expect(item.length).toBeLessThanOrEqual(120);
  });

  it("comes back out exactly, so a cleared label leaves the body as it was", () => {
    expect(withoutLaneAsk(withLaneAsk(FOLDED, "Pick?"))).toBe(FOLDED);
    expect(withoutLaneAsk(withLaneAsk(SESSION_BODY, "Pick?"))).toBe(SESSION_BODY);
    expect(withoutLaneAsk(FOLDED)).toBe(FOLDED);
  });
});

describe("a lane that comments and labels gets its ask lifted into the body", () => {
  const NOW = Date.parse("2026-11-01T12:00:00Z");
  const LANE = "skynet-envoy[bot]";
  const said = (body: string, over: Record<string, unknown> = {}) => ({
    body,
    html_url: "https://github.com/o/r/issues/77#issuecomment-1",
    created_at: "2026-11-01T11:59:00Z",
    user: { login: LANE, type: "Bot" },
    ...over,
  });
  const labeled = (body = "**Ask.**", sender = LANE) => ({
    payload: {
      issue: { number: 77, body, labels: [{ name: "needs-eric" }, { name: "ready" }] },
      sender: { login: sender },
    },
  });
  const spy = (comments: unknown[], live = "**Ask.**") => {
    const writes: [number, string][] = [];
    const posts: [number, string][] = [];
    return {
      writes,
      posts,
      deps: {
        now: NOW,
        readComments: () => comments,
        readBody: () => live,
        writeBody: (n: number, body: string) => void writes.push([n, body]),
        post: (n: number, body: string) => void posts.push([n, body]),
      },
    };
  };

  it("takes the lane's own newest comment, drops the gap comment, and reads Blocked after", () => {
    const { writes, posts, deps } = spy([said("**Merge #5 or close it?** It is protected.")]);
    expect(checkCallout(labeled(), deps)).toMatchObject({ lifted: true, posted: false });
    expect(posts).toEqual([]);
    expect(writes[0]?.[1]).toContain("> 1. **Merge #5 or close it?** It is protected.");
    expect(writes[0]?.[1]).toContain("#issuecomment-1");
    const after = {
      number: 77,
      state: "open",
      labels: ["needs-eric", "ready"],
      body: writes[0]?.[1],
    };
    expect(wantedStatusOf(after)).toBe("Blocked");
  });

  it("writes from the live body, so an edit since the event is not lost", () => {
    const { writes, deps } = spy([said("Pick?")], "**Edited since the event.**");
    checkCallout(labeled(), deps);
    expect(writes[0]?.[1]).toContain("**Edited since the event.**");
  });

  it("stays silent when the live body already states it", () => {
    const live = "> [!IMPORTANT]\n> **Needs from you**\n> 1. Written since?\n";
    const { writes, posts, deps } = spy([said("Pick?")], live);
    checkCallout(labeled(), deps);
    expect(writes).toEqual([]);
    expect(posts).toEqual([]);
  });

  it.each([
    [
      "a person's comment: a public repo's stranger never writes his queue",
      said("x", { user: { login: "stranger", type: "User" } }),
    ],
    [
      "the lane's start-of-build notice, which asks nothing",
      said("A plan build session has started on slice 2."),
    ],
    [
      "a comment too old to belong to this label",
      said("Pick?", { created_at: "2026-10-01T00:00:00Z" }),
    ],
  ])("falls back to the gap comment on %s", (_why, comment) => {
    const { writes, posts, deps } = spy([comment]);
    expect(checkCallout(labeled(), deps)).toMatchObject({ posted: true });
    expect(writes).toEqual([]);
    expect(posts).toHaveLength(1);
  });

  it("never lifts its own gap comment, and does not repeat it", () => {
    const { writes, posts, deps } = spy([said(`x\n${CALLOUT_GAP_MARKER}`)]);
    expect(checkCallout(labeled(), deps)).toMatchObject({ posted: false });
    expect(writes).toEqual([]);
    expect(posts).toEqual([]);
  });

  it("never lifts for a person's label: they can write the callout, so the comment asks them to", () => {
    const { writes, posts, deps } = spy([
      said("Pick?", { user: { login: "ejclark", type: "User" } }),
    ]);
    expect(checkCallout(labeled("**Ask.**", "ejclark"), deps)).toMatchObject({ posted: true });
    expect(writes).toEqual([]);
    expect(posts).toHaveLength(1);
  });

  it("reads the first real line, not a marker or a heading's hashes", () => {
    const comment = said("<!-- marker -->\n\n## The ask\nmore");
    expect(askFromComments([comment], { actor: LANE, now: NOW })?.line).toBe("The ask");
  });
});

