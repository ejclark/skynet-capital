// The post-merge audit of #6562. `needs-eric` promises a decision only he can make, and rule 7 says
// where it lives: one callout, above the fold. The lanes that apply the label wrote the ask in a
// comment, so a parked plan read Waiting and held a started-plan seat. The rule's footer test also
// missed session-written issues, and two overlapping sweeps posted the same ask twice.
const SESSION_BODY = "**Ask.**\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
const parkedLabels = ["plan", "ready", "next-slice", "needs-eric"];
const parkedPlan = (number: number, body = SESSION_BODY) => ({
  number,
  title: `plan ${number}`,
  state: "open",
  body,
  labels: parkedLabels.map((name) => ({ name })),
  user: { login: "ejclark" },
  sub_issues_summary: { total: 3, completed: 1 },
  openSubIssues: [{ number: number + 100, labels: [] }],
});
const STOP = {
  kind: "stop-continuation" as const,
  issueNumber: 1,
  title: "a plan",
  reason: "the continued slice's run concluded `failure`",
  runUrl: "https://run/900",
  body: "the stop comment",
};

const stated = (body: string) => !missingDecisionCallout({ labels: ["needs-eric"], body });
const noop = () => undefined;

/** Records every write. */
const stubGithub = () => {
  const calls: string[][] = [];
  const run = (cmd: string, args: readonly string[]) => {
    calls.push([cmd, ...args]);
    return "";
  };
  return { calls, run, retry: <T>(fn: () => T) => fn() };
};
const bodyWrites = (calls: string[][]) =>
  calls.filter((c) => c.includes("PATCH")).map((c) => String(c.at(-1)).replace(/^body=/, ""));

describe("a plan the lane parks is in his queue, stated once, and holds no seat", () => {
  it("writes the ask into the body before the label lands", () => {
    const { calls, run, retry } = stubGithub();
    const live = { ...parkedPlan(1), labels: [{ name: "plan" }, { name: "ready" }] };
    executeStopContinuation(STOP, { run, retry, read: () => live, assign: () => "assigned" });

    const patch = calls.findIndex((c) => c.includes("PATCH"));
    const label = calls.findIndex((c) => c.includes("--add-label"));
    expect(patch).toBeGreaterThanOrEqual(0);
    // The `labeled` event's payload is what the gap check reads, so body first means no false alarm.
    expect(patch).toBeLessThan(label);
  });

  it("reads Blocked, takes no seat and draws no gap comment once parked (the audit's repro)", () => {
    const { calls, run, retry } = stubGithub();
    const live = { ...parkedPlan(1), labels: [{ name: "plan" }, { name: "ready" }] };
    executeStopContinuation(STOP, { run, retry, read: () => live, assign: () => "assigned" });
    const [body] = bodyWrites(calls);
    const issue = { ...parkedPlan(1, body as string) };

    expect(wantedStatusOf(issue)).toBe("Blocked");
    expect(waitingPlans([issue])).toEqual([]);
    expect(
      shouldPostCalloutGap({
        labels: parkedLabels,
        body,
        comments: [stopComment({ reason: "x", runUrl: "" } as never)],
      }),
    ).toBe(false);
  });

  it("reaches the needs-you list with the ask it wrote", () => {
    const { calls, run, retry } = stubGithub();
    const live = { ...parkedPlan(1), labels: [{ name: "plan" }, { name: "ready" }] };
    executeStopContinuation(STOP, { run, retry, read: () => live, assign: () => "assigned" });
    const [body] = bodyWrites(calls);

    const { needsYou } = plan({
      issues: [{ ...parkedPlan(1, body as string), assignees: [{ login: "ejclark" }] }],
      markers: new Set([1]),
    });
    expect(needsYou.map((n) => n.decision)).toEqual([
      expect.stringContaining("Resume this plan, or say what to fix first?"),
    ]);
  });

  it("does nothing when another sweep already parked it", () => {
    const { calls, run, retry } = stubGithub();
    let assigned = 0;
    executeStopContinuation(STOP, {
      run,
      retry,
      read: () => parkedPlan(1),
      assign: () => {
        assigned += 1;
        return "assigned";
      },
    });
    expect(calls).toEqual([]);
    expect(assigned).toBe(0);
  });

  // However the label landed — a person in the GitHub UI, a lane that said nothing — the plan cannot
  // be pulled, so the cap has nothing to wait for. The audit's admitBuild refusal, kept as a pin.
  it("a parked plan with no callout at all still holds no seat", () => {
    const plans = [1, 2, 3, 4].map((n) => parkedPlan(n));
    expect(waitingPlans(plans)).toEqual([]);
    const fresh = { number: 50, body: "", labels: [{ name: "plan" }, { name: "ready" }] };
    const mode = { position: "normal" as const, caps: { inFlightCap: 3, startedPlanCap: 4 } };
    expect(admitBuild({ issue: fresh, mode, waiting: waitingPlans(plans) }).admit).toBe(true);
  });

  it("an unparked plan keeps its seat, so the cap is not loosened", () => {
    const idle = {
      ...parkedPlan(1),
      labels: [{ name: "plan" }, { name: "ready" }],
    };
    expect(waitingPlans([idle]).map((p) => p.number)).toEqual([1]);
    expect(
      statusForIssue({ labels: ["plan", "ready"], subIssues: { total: 3, completed: 1 } }),
    ).toBe("Waiting");
  });
});

