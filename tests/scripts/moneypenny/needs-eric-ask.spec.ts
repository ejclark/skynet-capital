// 2026-11-01 14:34Z, #4621 and #5709: a push sweep and a `scan` dispatch run in separate concurrency
// groups (#5130). Each read no marker, then each wrote one, 6 seconds apart.
describe("two overlapping sweeps post one ask", () => {
  const INTENT = {
    kind: "assign-eric",
    number: 7,
    criterion: 1,
    why: "w",
    body: `the ask ${ASSIGN_MARKER}`,
  } as const;
  const bot = { user: { type: "Bot" }, author_association: "NONE" };

  /** A shared GitHub both sweeps write to, with a lease that is a real compare-and-set. */
  const github = () => {
    const comments: { body: string }[] = [];
    const held = new Set<string>();
    let onWrite: () => void = noop;
    return {
      comments,
      set onWrite(fn: () => void) {
        onWrite = fn;
      },
      rest: () => comments.map((c) => ({ ...c, ...bot })),
      run: (_cmd: string, args: readonly string[]) => {
        if (String(args[3]).endsWith("/comments")) {
          comments.push({ body: String(args.at(-1)).replace(/^body=/, "") });
        }
        onWrite();
        return "";
      },
      retry: <T>(fn: () => T) => fn(),
      lease: {
        claim: (slug: string) => {
          if (held.has(slug)) return { claimed: false, reason: "held by a live claim (0m old)" };
          held.add(slug);
          return { claimed: true, reason: "claimed" };
        },
        release: (slug: string) => held.delete(slug),
      },
    };
  };
  const asks = (comments: { body: string }[]) =>
    comments.filter((c) => c.body.includes("the ask")).length;

  it("the writes alone post twice from two stale reads: the cause", () => {
    const gh = github();
    executeAssignments(INTENT, gh);
    executeAssignments(INTENT, gh);
    expect(asks(gh.comments)).toBe(2);
  });

  it("the second sweep re-reads before writing and stands down (the 6-second case)", () => {
    const gh = github();
    askOnce(INTENT, gh);
    const line = askOnce(INTENT, gh);
    expect(asks(gh.comments)).toBe(1);
    expect(line).toMatch(/already/);
  });

  it("the lease stops a sweep that reads between the other's two writes", () => {
    const gh = github();
    let inner = "";
    gh.onWrite = () => {
      gh.onWrite = noop;
      inner = askOnce(INTENT, gh); // the assignment landed; its comment has not
    };
    askOnce(INTENT, gh);
    expect(asks(gh.comments)).toBe(1);
    expect(inner).toMatch(/another sweep/);
  });

  it("releases the lease when a write throws, so the next tick can ask", () => {
    const gh = github();
    gh.onWrite = () => {
      throw new Error("500");
    };
    expect(() => askOnce(INTENT, gh)).toThrow("500");
    gh.onWrite = noop;
    askOnce(INTENT, gh);
    expect(asks(gh.comments)).toBe(1);
  });

  it("a lease GitHub refuses never costs him the ask: a duplicate beats a lost decision", () => {
    const gh = github();
    const lease = {
      claim: () => ({ claimed: false, reason: "could not create the lease — HTTP 403" }),
      release: () => false,
    };
    askOnce(INTENT, { ...gh, lease });
    expect(asks(gh.comments)).toBe(1);
  });

  it("an unassign stands down when the other sweep already cleared it", () => {
    const gh = github();
    const out = { kind: "unassign-eric", number: 7, criterion: 2, why: "issue closed" } as const;
    gh.comments.push({ body: `asked ${ASSIGN_MARKER}` });
    askOnce(out, { ...gh, read: () => ({ body: "" }) });
    askOnce(out, { ...gh, read: () => ({ body: "" }) });
    expect(gh.comments.filter((c) => c.body.includes(UNASSIGN_MARKER))).toHaveLength(1);
  });

  it("clearing the label also takes the lane's ask back out of the body", () => {
    const gh = github();
    const out = {
      kind: "unassign-eric",
      number: 7,
      criterion: 2,
      why: "needs-eric removed",
    } as const;
    gh.comments.push({ body: `asked ${ASSIGN_MARKER}` });
    const writes: string[] = [];
    const run = (cmd: string, args: readonly string[]) => {
      if (args.includes("PATCH")) writes.push(String(args.at(-1)).replace(/^body=/, ""));
      return gh.run(cmd, args);
    };
    askOnce(out, { ...gh, run, read: () => ({ body: withLaneAsk("**Ask.**", "Pick?") }) });
    expect(writes).toEqual(["**Ask.**"]);
  });
});

// The real router, with `gh` and `curl` stubbed: injected fakes above cannot see whether `executeOne`
// hands the lease over, which is the half that closes the race on a runner.
describe("the sweep's executor takes the lease (wiring)", () => {
  let dir: string;
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), "ask-lease-"));
    writeFileSync(
      join(dir, "gh"),
      [
        "#!/bin/sh",
        `printf '%s\\n' "$*" >> "${dir}/gh.log"`,
        'case "$*" in',
        '  *"git/ref/tags/claim/"*) [ -f "$HELD" ] && echo \'{"object":{"sha":"held"}}\' || exit 1 ;;',
        `  *"git/tags/held"*) printf '{"tagger":{"date":"%s"}}' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" ;;`,
        `  *"git/tags"*) echo '{"sha":"stamp"}' ;;`,
        "  *) echo '{}' ;;",
        "esac",
        "",
      ].join("\n"),
    );
    writeFileSync(
      join(dir, "curl"),
      [
        "#!/bin/sh",
        'case "$*" in',
        "  *comments*) echo '[]' ;;",
        `  *) echo '{"body":"**Ask.**","labels":[{"name":"plan"}]}' ;;`,
        "esac",
        "",
      ].join("\n"),
    );
    chmodSync(join(dir, "gh"), 0o755);
    chmodSync(join(dir, "curl"), 0o755);
  });
  afterEach(() => rmSync(dir, { recursive: true, force: true }));

  const runOne = (intent: unknown, held = false) => {
    const out = spawnSync(
      "node",
      [
        "-e",
        `import("./scripts/moneypenny/index.mjs").then((m) => m.executeOne(JSON.parse(process.argv[1])));`,
        JSON.stringify(intent),
      ],
      {
        encoding: "utf8",
        env: {
          ...process.env,
          PATH: `${dir}:${process.env.PATH}`,
          GH_TOKEN: "t",
          GITHUB_SHA: "abc123",
          HELD: held ? join(dir, "gh") : join(dir, "absent"),
        },
      },
    );
    expect(out.status, out.stderr).toBe(0);
    return readFileSync(join(dir, "gh.log"), "utf8").trim().split("\n");
  };
  const ASSIGN = { kind: "assign-eric", number: 7, criterion: 1, why: "w", body: "the ask" };
  const STOP_INTENT = { ...STOP, issueNumber: 7 };

  it("an ask takes the lease, writes under it, then gives it back", () => {
    const log = runOne(ASSIGN);
    const at = (s: string) => log.findIndex((l) => l.includes(s));
    expect(at("git/refs")).toBeGreaterThanOrEqual(0);
    expect(at("git/refs")).toBeLessThan(at("issues/7/assignees"));
    expect(at("issues/7/comments")).toBeLessThan(at("-X DELETE"));
    expect(log.at(-1)).toContain("git/refs/tags/claim/ask-7");
  });

  it("an ask writes nothing while another sweep holds the lease", () => {
    const log = runOne(ASSIGN, true);
    expect(log.filter((l) => l.includes("issues/7/"))).toEqual([]);
  });

  it("a stop writes nothing while another sweep holds the lease", () => {
    const log = runOne(STOP_INTENT, true);
    expect(log.filter((l) => /issues\/7|issue edit/.test(l))).toEqual([]);
  });

  it("a stop states the ask, labels, then assigns, under the lease", () => {
    const log = runOne(STOP_INTENT);
    const at = (s: string) => log.findIndex((l) => l.includes(s));
    expect(at("--method PATCH")).toBeGreaterThanOrEqual(0);
    expect(at("--method PATCH")).toBeLessThan(at("--add-label"));
    expect(at("--add-label")).toBeLessThan(at("issues/7/assignees"));
    expect(log.at(-1)).toContain("git/refs/tags/claim/ask-7");
  });
});
