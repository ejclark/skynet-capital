import { describe, expect, it } from "@rstest/core";
import type { Answer } from "../../../scripts/moneypenny/answer-readback.mjs";
import {
  appendRows,
  executeReadback,
  findReply,
  ledgerRows,
  READ_MARKER,
  readAnswer,
  readbackComment,
  readbackFor,
  rowsFromComments,
} from "../../../scripts/moneypenny/answer-readback.mjs";
import {
  assignmentComment,
  cardOf,
  parseAsk,
  UNASSIGN_MARKER,
} from "../../../scripts/moneypenny/ask-card.mjs";

// #6953 slice 3: his reply, read on the push tick, clears the ask and scores the ledger.
const CALLOUT = [
  "> [!IMPORTANT]",
  "> **Needs from you**",
  "> 1. Re-arm the breaker? — a bot safety rule",
  ">    - A (predicted, medium): yes, at the next session",
  ">    - B: no, stay latched",
].join("\n");
const TWO = `${CALLOUT}\n> 2. Second?\n>    - A: x\n>    - C (predicted, low): y`;
const ASK = assignmentComment({ items: parseAsk(CALLOUT) });
const card = cardOf;
const bot = (body: string, at = "2026-11-07T00:00:00Z") => ({
  body,
  user: { type: "Bot", login: "skynet-envoy[bot]" },
  author_association: "NONE",
  created_at: at,
});
const his = (body: string, at = "2026-11-07T01:00:00Z", over = {}) => ({
  id: 77,
  body,
  user: { type: "User", login: "ejclark" },
  author_association: "OWNER",
  created_at: at,
  ...over,
});

describe("readAnswer: what his first line says", () => {
  const one = card(ASK);
  it("reads a letter on the card, with trailing words", () => {
    expect(readAnswer("A", one)).toEqual({ kind: "option", picks: [{ item: 0, key: "A" }] });
    expect(readAnswer("b — keep it simple", one)).toEqual({
      kind: "option",
      picks: [{ item: 0, key: "B" }],
    });
    expect(readAnswer("> **Reply: A**", one)?.kind).toBe("option");
  });

  it("does not read a letter the card never offered, nor a bare yes against lettered options", () => {
    expect(readAnswer("C", one)).toBeNull();
    expect(readAnswer("yes", one)).toBeNull();
    expect(readAnswer("What does A mean?", one)).toBeNull();
  });

  it("reads not now whatever the card", () => {
    expect(readAnswer("Not now", one)).toEqual({ kind: "deferred" });
  });

  it("reads yes and no only where no letter is on offer", () => {
    const plain = card(assignmentComment({ decision: "Press the button." }));
    expect(readAnswer("Yes, done", plain)).toEqual({ kind: "yes" });
    expect(readAnswer("no", plain)).toEqual({ kind: "no" });
  });

  it("reads one letter per question, in order or numbered", () => {
    const two = card(assignmentComment({ items: parseAsk(TWO) }));
    expect(readAnswer("A, C", two)).toEqual({
      kind: "option",
      picks: [
        { item: 0, key: "A" },
        { item: 1, key: "C" },
      ],
    });
    expect(readAnswer("2C 1B", two)).toEqual({
      kind: "option",
      picks: [
        { item: 1, key: "C" },
        { item: 0, key: "B" },
      ],
    });
    expect(readAnswer("A", two)).toBeNull();
    expect(readAnswer("A, because", two)).toBeNull();
  });
});

describe("findReply: whose words count", () => {
  it("returns his first readable reply after the ask", () => {
    const found = findReply([
      bot(ASK),
      his("let me think", "2026-11-07T01:00:00Z"),
      his("B", "2026-11-07T02:00:00Z"),
    ]);
    expect(found?.answer).toEqual({ kind: "option", picks: [{ item: 0, key: "B" }] });
  });

  it("ignores a session posting under his login (it carries the lane footer)", () => {
    const session = his("A\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_");
    expect(findReply([bot(ASK), session])).toBeNull();
  });

  it("ignores a stranger, an older comment and a closed ask", () => {
    const stranger = his("A", "2026-11-07T01:00:00Z", {
      user: { type: "User", login: "someone" },
      author_association: "NONE",
    });
    expect(findReply([bot(ASK), stranger])).toBeNull();
    expect(findReply([his("A", "2026-11-06T01:00:00Z"), bot(ASK)])).toBeNull();
    expect(
      findReply([bot(ASK), bot(`done\n${UNASSIGN_MARKER}`, "2026-11-07T00:30:00Z"), his("A")]),
    ).toBeNull();
  });

  it("does not believe a card a person wrote", () => {
    const forged = {
      ...bot(ASK),
      user: { type: "User", login: "ejclark" },
      author_association: "OWNER",
    };
    expect(findReply([forged, his("A")])).toBeNull();
  });
});

describe("readbackFor: which issues are the lane's to read", () => {
  const issue = (labels: string[]) => ({ number: 5, title: "t", state: "open", labels });
  const thread = [bot(ASK), his("A")];
  it("reads a needs-eric issue", () => {
    expect(readbackFor(issue(["needs-eric"]), thread)?.number).toBe(5);
  });
  it("leaves plan and feedback issues to reply-resume, and an issue without the label alone", () => {
    expect(readbackFor(issue(["needs-eric", "plan"]), thread)).toBeNull();
    expect(readbackFor(issue(["needs-eric", "feedback"]), thread)).toBeNull();
    expect(readbackFor(issue([]), thread)).toBeNull();
  });
});

describe("the ledger row", () => {
  const reply = his("A");
  const base = { number: 5, title: "t", reply };
  it("scores a letter against the predicted letter", () => {
    const [row] = ledgerRows({
      ...base,
      card: card(ASK),
      answer: { kind: "option", picks: [{ item: 0, key: "A" }] },
    });
    expect(row).toMatchObject({
      date: "2026-11-07",
      cls: "bot safety rules",
      given: "A",
      score: "match",
    });
    const [miss] = ledgerRows({
      ...base,
      card: card(ASK),
      answer: { kind: "option", picks: [{ item: 0, key: "B" }] },
    });
    expect(miss?.score).toBe("miss");
  });
  it("does not score a deferral as a miss, nor a prose prediction by guess", () => {
    expect(
      ledgerRows({ ...base, card: card(ASK), answer: { kind: "deferred" } })[0]?.score,
    ).toMatch(/^unclear/);
    const none = card(assignmentComment({ decision: "Q?" }));
    expect(ledgerRows({ ...base, card: none, answer: { kind: "yes" } })[0]?.score).toBe(
      "not predicted",
    );
  });
  it("makes one row per question answered", () => {
    const two = card(assignmentComment({ items: parseAsk(TWO) }));
    const rows = ledgerRows({
      ...base,
      card: two,
      answer: {
        kind: "option",
        picks: [
          { item: 0, key: "A" },
          { item: 1, key: "A" },
        ],
      },
    });
    expect(rows.map((r) => r.score)).toEqual(["match", "miss"]);
  });
});

describe("readbackComment and executeReadback", () => {
  const answer: Answer = { kind: "option", picks: [{ item: 0, key: "A" }] };
  const rows = ledgerRows({ number: 5, title: "t", reply: his("A"), card: card(ASK), answer });
  const comment = readbackComment({ answer, rows });

  it("says what it read, and unmarks the ask so a returning label asks afresh", () => {
    expect(comment).toContain("Read as: A.");
    expect(comment).toContain(READ_MARKER);
    expect(comment).toContain(UNASSIGN_MARKER);
  });

  it("takes the label off, unassigns him, then answers last", () => {
    const calls: string[][] = [];
    const run = (_cmd: string, args: readonly string[]) => {
      calls.push([...args]);
      return "";
    };
    const line = executeReadback(
      { number: 5, body: comment, said: "Read as: A." },
      { run, retry: (fn) => fn(), read: () => ({ body: "x" }) },
    );
    expect(line).toContain("#5");
    const verbs = calls.map((c) => `${c[2]} ${(c[3] ?? "").replace("repos/{owner}/{repo}/", "")}`);
    expect(verbs).toEqual([
      "DELETE issues/5/labels/needs-eric",
      "DELETE issues/5/assignees",
      "POST issues/5/comments",
    ]);
  });

  it("carries on when the label is already gone", () => {
    let n = 0;
    const run = (_cmd: string, args: readonly string[]) => {
      n++;
      if (args.includes("DELETE") && args[3]?.includes("labels"))
        throw new Error("HTTP 404 Not Found");
      return "";
    };
    expect(() =>
      executeReadback(
        { number: 5, body: comment },
        { run, retry: (fn) => fn(), read: () => ({ body: "" }) },
      ),
    ).not.toThrow();
    expect(n).toBe(3);
  });
});

describe("collecting rows into the ledger", () => {
  const ledger = "| Date | Class |\n|---|---|\n| 2026-10-18 | x |\n\nProse after.";
  const answer: Answer = { kind: "option", picks: [{ item: 0, key: "A" }] };
  const rows = ledgerRows({ number: 5, title: "t", reply: his("A"), card: card(ASK), answer });
  const found = rowsFromComments([bot(readbackComment({ answer, rows }))]);

  it("reads rows back out of the lane's own comments", () => {
    expect(found).toHaveLength(1);
    expect(rowsFromComments([his(readbackComment({ answer, rows }))])).toEqual([]);
  });

  it("appends each row once, to the table", () => {
    const once = appendRows(ledger, found);
    expect(once.added).toBe(1);
    expect(once.ledger.indexOf("| 2026-11-07")).toBeLessThan(once.ledger.indexOf("Prose after."));
    expect(appendRows(once.ledger, found).added).toBe(0);
  });
});
