const ISSUES = resolve("scripts/issues.mjs");

// The issue CLI's pure core: the parts that decide whether a filing is refused, what the board
// column reads, and which labels an edit leaves — proven without calling GitHub.
describe("issues cli: parseArgs", () => {
  it("splits the command, positionals, value flags and boolean flags", () => {
    const out = parseArgs(["update", "42", "--add", "needs-eric,bug", "--reopen"]);
    expect(out).toEqual({
      cmd: "update",
      positional: ["42"],
      flags: { add: "needs-eric,bug", reopen: true },
    });
  });
});

describe("issues cli: findDuplicates", () => {
  const open = [
    { number: 1, title: "Add Dependabot secrets so dependency PRs get reviewed and merged" },
    { number: 2, title: "Freeze the research screenshot fixture" },
  ];

  it("flags an open issue asking the same thing in different punctuation", () => {
    const hits = findDuplicates(
      "Add dependabot secrets — so dependency PRs get reviewed & merged",
      open,
    );
    expect(hits.map((h) => h.number)).toEqual([1]);
  });

  it("lets a merely related title through", () => {
    expect(findDuplicates("Stop running route on Dependabot PRs", open)).toEqual([]);
  });

  it("never matches an empty or all-stopword title", () => {
    expect(findDuplicates("a b", open)).toEqual([]);
    expect(titleWords("a b").size).toBe(0);
  });
});

describe("issues cli: board status follows labels", () => {
  const CALLOUT = "> [!IMPORTANT]\n> **Needs from you**\n> 1. Pick A or B?";

  it("reads needs-eric as Blocked, ready as Ready, closed as Done", () => {
    expect(
      boardStatus({ title: "x", state: "open", labels: [{ name: "needs-eric" }], body: CALLOUT }),
    ).toBe("Blocked");
    expect(boardStatus({ title: "x", state: "open", labels: ["ready"] })).toBe("Ready");
    expect(boardStatus({ title: "x", state: "closed", labels: ["needs-eric"] })).toBe("Done");
    expect(boardStatus({ title: "x", state: "open", labels: [] })).toBe("Backlog");
  });

  // #3913 slice 2: the board keeps an unstated ask out of Blocked until the callout is written.
  it("keeps a needs-eric issue with no callout out of Blocked, unless Eric filed it", () => {
    const labels = [{ name: "needs-eric" }];
    expect(boardStatus({ title: "x", state: "open", labels, body: "no ask" })).toBe("Backlog");
    expect(
      boardStatus({ title: "x", state: "open", labels, body: "", user: { login: "ejclark" } }),
    ).toBe("Blocked");
  });

  it("prints one scan-able row per issue", () => {
    expect(row({ number: 7, title: "T", state: "open", labels: [{ name: "needs-info" }] })).toBe(
      "#7 [Blocked] T  (needs-info)",
    );
  });
});

describe("issues cli: edits", () => {
  it("adds and removes labels without duplicating", () => {
    expect(nextLabels(["a", "b"], ["b", "c"], ["a"])).toEqual(["b", "c"]);
  });

  it("parses comma lists, dropping blanks", () => {
    expect(csv(" a, ,b ")).toEqual(["a", "b"]);
    expect(csv(undefined)).toEqual([]);
  });

  it("appends the attribution footer once", () => {
    const once = withFooter("body");
    expect(once).toContain("Generated by [Claude Code]");
    expect(withFooter(once)).toBe(once);
  });

  it("posts a new footered comment, or edits one in place with --edit-comment (#4537)", () => {
    expect(commentWrite({ n: 7, body: "hi" })).toEqual({
      method: "POST",
      path: "issues/7/comments",
      payload: { body: withFooter("hi") },
    });
    const edit = commentWrite({ n: 7, body: "### State\nLog", editId: "6074658599" });
    expect(edit.method).toBe("PATCH");
    expect(edit.path).toBe("issues/comments/6074658599");
    // the footer is the marker claude.yml's gate skips on — an edit must carry it too
    expect(edit.payload.body).toContain("[Claude Code](https://claude");
    const signed = withFooter("x");
    expect(commentWrite({ n: 7, body: signed, editId: 1 }).payload.body).toBe(signed);
    const argv = ["update", "7", "--edit-comment", "42", "--comment-file", "c.md"];
    expect(parseArgs(argv).flags).toEqual({ "edit-comment": "42", "comment-file": "c.md" });
  });

  it("refuses an --edit-comment that is not a comment id", () => {
    expect(() => commentWrite({ n: 7, body: "x", editId: "" })).toThrow(/comment id/);
    expect(() => commentWrite({ n: 7, body: "x", editId: "abc" })).toThrow(/comment id/);
  });

  // #6285: what parseArgs really yields, not a hand-built flags object.
  const opFor = (...argv: string[]) =>
    updateCommentOp({ n: 7, flags: parseArgs(["update", "7", ...argv]).flags, read: () => "b" });

  it("refuses a trailing --edit-comment with no id instead of posting a new comment", () => {
    const flags = parseArgs(["update", "7", "--comment-file", "c.md", "--edit-comment"]).flags;
    expect("edit-comment" in flags).toBe(true);
    expect(() => opFor("--comment-file", "c.md", "--edit-comment")).toThrow(/comment id/);
    expect(() =>
      opFor("--comment-file", "c.md", "--edit-comment", "issuecomment-6074658599"),
    ).toThrow(/comment id/);
  });

  it("plans the comment write from parsed flags: post, edit, or none", () => {
    expect(opFor("--comment-file", "c.md")?.method).toBe("POST");
    expect(opFor("--edit-comment", "42", "--comment-file", "c.md")?.path).toBe(
      "issues/comments/42",
    );
    expect(opFor("--add", "bug")).toBeNull();
    expect(() => opFor("--edit-comment", "42")).toThrow(/needs --comment-file/);
  });

  it("refuses a bad --edit-comment before the issue PATCH runs", () => {
    const dir = mkdtempSync(join(tmpdir(), "issues-6285-"));
    const log = join(dir, "curl.log");
    // a stub curl: logs every call and answers like an issue read
    writeFileSync(
      join(dir, "curl"),
      `#!/bin/sh\necho "$@" >> "${log}"\ncat >/dev/null\necho '{"number":7,"title":"t","state":"open","labels":[]}'\n`,
    );
    chmodSync(join(dir, "curl"), 0o755);
    writeFileSync(join(dir, "c.md"), "block");
    const argv = ["update", "7", "--close", "completed"];
    const res = spawnSync(
      process.execPath,
      [
        ISSUES,
        ...argv,
        "--edit-comment",
        "issuecomment-6074658599",
        "--comment-file",
        join(dir, "c.md"),
      ],
      {
        env: { ...process.env, PATH: `${dir}:${process.env.PATH}`, GH_TOKEN: "stub" },
        encoding: "utf8",
      },
    );
    expect(res.status).toBe(1);
    expect(res.stderr).toMatch(/comment id/);
    expect(existsSync(log) ? readFileSync(log, "utf8") : "").toBe("");
  });

  it("matches every word across title and body, and filters by label", () => {
    const issue = {
      title: "Add Dependabot secrets",
      body: "dep-warden login",
      labels: ["needs-eric"],
    };
    expect(matches(issue, "dependabot login")).toBe(true);
    expect(matches(issue, "dependabot deploy")).toBe(false);
    expect(matches(issue, "", { label: "needs-eric" })).toBe(true);
    expect(matches(issue, "", { label: "ready" })).toBe(false);
  });
});

describe("issues cli: followUps (slices as sub-issues)", () => {
  const child = { id: 9001, number: 42 };

  it("links to the parent, adds each blocker, then closes a shipped slice — in that order", () => {
    const ops = followUps({ child, parentNumber: 7, blockers: [{ id: 11 }], closed: true });
    expect(ops.map((o) => `${o.method} ${o.path}`)).toEqual([
      "POST issues/7/sub_issues",
      "POST issues/42/dependencies/blocked_by",
      "PATCH issues/42",
    ]);
    expect(ops[0]?.payload).toEqual({ sub_issue_id: 9001 });
    expect(ops[1]?.payload).toEqual({ issue_id: 11 });
    expect(ops[2]?.payload).toEqual({ state: "closed", state_reason: "completed" });
  });

  it("writes nothing for a plain filing", () => {
    expect(followUps({ child })).toEqual([]);
  });

  // #5266 — `ready` fires the claim lanes, so it lands only after every link exists.
  it("adds the held-back labels after every link and before the close", () => {
    const ops = followUps({
      child,
      parentNumber: 7,
      blockers: [{ id: 11 }, { id: 12 }],
      afterLinks: ["ready"],
      closed: true,
    });
    expect(ops.map((o) => `${o.method} ${o.path}`)).toEqual([
      "POST issues/7/sub_issues",
      "POST issues/42/dependencies/blocked_by",
      "POST issues/42/dependencies/blocked_by",
      "POST issues/42/labels",
      "PATCH issues/42",
    ]);
    expect(ops[3]?.payload).toEqual({ labels: ["ready"] });
  });
});

describe("issues cli: splitLabels (#5266 — ready waits for the links)", () => {
  const labels = ["feedback", "ready", "bug"];

  it("holds `ready` back when the filing has a blocker", () => {
    expect(splitLabels(labels, { blockers: [{ id: 11 }] })).toEqual({
      initial: ["feedback", "bug"],
      afterLinks: ["ready"],
    });
  });

  it("holds `ready` back when the filing has a parent", () => {
    expect(splitLabels(labels, { parentNumber: 7 }).afterLinks).toEqual(["ready"]);
  });

  it("files every label at once when there is nothing to link", () => {
    expect(splitLabels(labels)).toEqual({ initial: labels, afterLinks: [] });
  });

  it("holds nothing back when the filing is not `ready`", () => {
    expect(splitLabels(["feedback"], { blockers: [{ id: 11 }] })).toEqual({
      initial: ["feedback"],
      afterLinks: [],
    });
  });
});

// #5196: closed/all passed ghRestAll's 2,000-row ceiling, so they ask GitHub's search instead.
describe("issues cli: search past the list ceiling", () => {
  const REPO = "ejclark/skynet-capital";

  it("builds the search query, leaving out state for all (state:all matches nothing)", () => {
    expect(searchQuery({ repo: REPO, words: "rtk tokens", state: "closed" })).toBe(
      `repo:${REPO} is:issue in:title,body state:closed rtk tokens`,
    );
    expect(searchQuery({ repo: REPO, words: "rtk", state: "all", label: "needs eric" })).toBe(
      `repo:${REPO} is:issue in:title,body label:"needs eric" rtk`,
    );
  });

  it("asks the search endpoint once, newest first, and keeps the first --limit hits", () => {
    const paths: string[] = [];
    const read = (path: string) => {
      paths.push(path);
      return { items: [1, 2, 3].map((n) => ({ number: n, title: `T${n}`, state: "closed" })) };
    };
    const items = searchRemote({ words: "rtk", state: "all", limit: 2, repo: REPO, read });
    expect(items.map((i) => i.number)).toEqual([1, 2]);
    expect(paths).toHaveLength(1);
    expect(paths[0]).toContain("https://api.github.com/search/issues?q=");
    expect(paths[0]).toContain("sort=created&order=desc&per_page=2");
    expect(decodeURIComponent(paths[0] ?? "")).toContain(`repo:${REPO} is:issue`);
  });

  it("pages the search when --limit is above 100, and stops on a short page", () => {
    let calls = 0;
    const read = () => {
      calls++;
      const n = calls === 1 ? 100 : 5;
      return { items: Array.from({ length: n }, (_, k) => ({ number: calls * 1000 + k })) };
    };
    const items = searchRemote({ words: "x", state: "closed", limit: 150, repo: REPO, read });
    expect(items).toHaveLength(105);
    expect(calls).toBe(2);
  });

  it("falls back to a list scan that stops once it has --limit matches, skipping PRs", () => {
    let pages = 0;
    const read = () => {
      pages++;
      return Array.from({ length: 100 }, (_, k) => ({
        number: k,
        title: k % 2 ? "rtk" : "other",
        ...(k === 1 ? { pull_request: {} } : {}),
      }));
    };
    const keep = (i: { title: string }) => i.title === "rtk";
    const scan = scanIssues("all", keep, 3, { read });
    expect(scan.items.map((i) => i.number)).toEqual([3, 5, 7]);
    expect(scan.partial).toBe(false);
    expect(pages).toBe(1);
  });

  it("says the scan was partial when it reaches the page ceiling short of --limit", () => {
    const read = () => Array.from({ length: 100 }, (_, k) => ({ number: k, title: "other" }));
    const scan = scanIssues("closed", () => false, 5, { read, maxPages: 2 });
    expect(scan).toEqual({ items: [], partial: true, scanned: 200 });
  });
});
