import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  liveSkip,
  malformed,
  planPosts,
  renderBody,
  unescapeHtml,
} from "../../scripts/clear-path-post.mjs";

// The write half of .claude/workflows/clear-path-flip.js (docs/ISSUES.md → Who may flip it): only a
// survivor with four passing checks and two verifier lines is ever posted, and anything malformed
// refuses the whole run before a write. Driven offline — the CLI path runs with --dry-run only.
const PASS = { pass: true, evidence: "x" };
const survivor = (over: Record<string, unknown> = {}) => ({
  issue: 6001,
  title: "add a thing",
  checks: { criteria: PASS, size: PASS, noFork: PASS, notBlocked: PASS },
  addFeedback: true,
  comment: "**Clear path — session flip**\n&lt;details&gt;why&lt;/details&gt;",
  verifiers: ["envelope — traced 2 paths, none protected", "thread — read 3 comments; clear"],
  ...over,
});

describe("unescapeHtml", () => {
  it("restores the entities subagent text arrives with", () => {
    expect(unescapeHtml("&lt;a href=&quot;x&quot;&gt;it&#39;s&lt;/a&gt;")).toBe(
      `<a href="x">it's</a>`,
    );
  });
  it("unescapes &amp; last, so a literally-escaped entity survives one level", () => {
    expect(unescapeHtml("&amp;lt; &amp;&amp;")).toBe("&lt; &&");
  });
});

describe("renderBody", () => {
  it("appends both verifier lines and the footer to the unescaped comment", () => {
    const body = renderBody(survivor());
    expect(body).toContain("<details>why</details>");
    expect(body).toContain("- envelope — traced 2 paths, none protected");
    expect(body).toContain("- thread — read 3 comments; clear");
    expect(body.trimEnd().endsWith("_Generated by [Claude Code](https://claude.ai/code)_")).toBe(
      true,
    );
  });
});

describe("malformed", () => {
  it("passes a well-formed survivor", () => {
    expect(malformed(survivor())).toBeNull();
  });
  it("refuses fewer than two distinct verifier lines", () => {
    expect(malformed(survivor({ verifiers: ["one"] }))).toMatch(/two distinct/);
    expect(malformed(survivor({ verifiers: ["same", "same"] }))).toMatch(/two distinct/);
    expect(malformed(survivor({ verifiers: ["a", "  "] }))).toMatch(/two distinct/);
  });
  it("refuses a failing or missing check", () => {
    const checks = { criteria: PASS, size: { pass: false }, noFork: PASS };
    expect(malformed(survivor({ checks }))).toMatch(/size, notBlocked/);
  });
  it("refuses an empty comment or a bad issue number", () => {
    expect(malformed(survivor({ comment: " " }))).toMatch(/comment/);
    expect(malformed(survivor({ issue: "6001" }))).toMatch(/issue number/);
  });
});

describe("planPosts", () => {
  it("posts survivors only, never refuted or not-clear entries", () => {
    const plan = planPosts({
      survivors: [survivor()],
      refuted: [{ issue: 6006, verifiers: ["a", "b"] }],
      notClear: [{ issue: 4458, failed: ["size"] }],
    });
    expect(plan.map((p) => p.issue)).toEqual([6001]);
  });
  it("adds feedback when the issue lacks it, and only ready when it already has it", () => {
    expect(planPosts({ survivors: [survivor()] })[0]?.labels).toEqual(["ready", "feedback"]);
    expect(planPosts({ survivors: [survivor({ addFeedback: false })] })[0]?.labels).toEqual([
      "ready",
    ]);
  });
  it("refuses the whole run when any survivor is malformed", () => {
    const result = { survivors: [survivor(), survivor({ issue: 6002, verifiers: ["one"] })] };
    expect(() => planPosts(result)).toThrow(/#6002/);
  });
  it("refuses a duplicate issue and a result that is not the workflow's shape", () => {
    expect(() => planPosts({ survivors: [survivor(), survivor()] })).toThrow(/twice/);
    expect(() => planPosts({})).toThrow(/survivors/);
  });
});

describe("liveSkip", () => {
  it("skips closed, already-ready and parked issues; passes an open clean one", () => {
    expect(liveSkip({ state: "closed", labels: [] })).toMatch(/closed/);
    expect(liveSkip({ state: "open", labels: [{ name: "ready" }] })).toMatch(/ready/);
    expect(liveSkip({ state: "open", labels: ["needs-eric"] })).toMatch(/needs-eric/);
    expect(liveSkip({ state: "open", labels: [{ name: "feedback" }] })).toBeNull();
    expect(liveSkip(null)).toMatch(/could not read/);
  });
});

describe("the CLI", () => {
  const run = (result: unknown, ...flags: string[]) => {
    const dir = mkdtempSync(join(tmpdir(), "clear-path-"));
    const file = join(dir, "result.json");
    writeFileSync(file, JSON.stringify(result));
    try {
      const out = execFileSync("node", ["scripts/clear-path-post.mjs", file, ...flags], {
        encoding: "utf8",
        stdio: "pipe",
      });
      return { out, code: 0 };
    } catch (error) {
      const e = error as { stdout?: string; stderr?: string; status?: number };
      return { out: `${e.stdout ?? ""}${e.stderr ?? ""}`, code: e.status ?? -1 };
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  };

  it("dry-runs a good result with exit 0 and prints the unescaped body", () => {
    const { out, code } = run({ survivors: [survivor()] }, "--dry-run");
    expect(code).toBe(0);
    expect(out).toContain("<details>why</details>");
    expect(out).toContain("1 would post");
  });
  it("exits 1 on a malformed survivor, before any write", () => {
    const { out, code } = run({ survivors: [survivor({ verifiers: [] })] }, "--dry-run");
    expect(code).toBe(1);
    expect(out).toMatch(/refusing the whole run/);
  });
  it("exits 0 with nothing to post when no call survived", () => {
    const { out, code } = run({ survivors: [], refuted: [{ issue: 1 }] });
    expect(code).toBe(0);
    expect(out).toMatch(/nothing to post/);
  });
});
