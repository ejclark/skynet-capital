import { describe, expect, it } from "@rstest/core";
import { readMarkers, respondMarker } from "../../../scripts/pr-review/markers.mjs";
import {
  gatherRespond,
  MAX_ROUNDS,
  type RespondInput,
  respondLine,
  routeRespond,
} from "../../../scripts/pr-review/respond-route.mjs";
import { fakeApi } from "./fake-api";

// #6870 S2. An open Important finding holds the merge only when a session is sent to answer it, so
// this routing decides whether the reviewer may hold at all. It copies red-session-pr.mjs's routing;
// each "no" below is one the plan names, and the last case is the one "yes".

const SHA = "abc1234def5678";
const REPO = { full_name: "ejclark/skynet-capital" };
const FOOTER = "🤖 Generated with [Claude Code](https://claude.com/claude-code)";
const pr = (over: Record<string, unknown> = {}) => ({
  number: 6870,
  state: "open",
  draft: false,
  labels: [],
  body: `Summary\n\n${FOOTER}`,
  author_association: "OWNER",
  user: { login: "ejclark", type: "User" },
  base: { ref: "main", repo: REPO },
  head: { ref: "claude/x", sha: SHA, repo: REPO },
  ...over,
});
const OPEN_GATE = { dispatch: true, position: "normal", reason: "" };
const route = (over: RespondInput = {}) =>
  routeRespond({
    pr: pr(),
    files: ["src/a.ts"],
    round: 1,
    importantOpen: 2,
    gate: OPEN_GATE,
    rules: [{ pattern: ".github/workflows/**" }],
    markers: readMarkers({}),
    ...over,
  });

describe("what gets no response session, and so never holds the merge", () => {
  const cases: [string, RespondInput, RegExp][] = [
    ["nothing Important is open", { importantOpen: 0 }, /nothing Important/],
    ["a closed PR", { pr: pr({ state: "closed" }) }, /no longer open/],
    ["a draft", { pr: pr({ draft: true }) }, /draft/],
    ["a held PR", { pr: pr({ labels: [{ name: "hold-merge" }] }) }, /hold-merge/],
    [
      "a PR aimed past main",
      { pr: pr({ base: { ref: "release", repo: REPO } }) },
      /aimed at `release`/,
    ],
    [
      "a fork",
      { pr: pr({ head: { ref: "x", sha: SHA, repo: { full_name: "someone/fork" } } }) },
      /fork/,
    ],
    [
      "dependabot's, by login",
      { pr: pr({ user: { login: "dependabot[bot]", type: "Bot" } }) },
      /dependabot/,
    ],
    [
      "dependabot's, by branch",
      { pr: pr({ head: { ref: "dependabot/npm/x", sha: SHA, repo: REPO } }) },
      /dependabot/,
    ],
    [
      "an outsider's",
      { pr: pr({ author_association: "NONE", user: { login: "someone", type: "User" } }) },
      /outside this repo/,
    ],
    ["one a person wrote", { pr: pr({ body: "my own words, no footer" }) }, /a person wrote/],
    [
      "one that changes a protected path",
      { files: ["src/a.ts", ".github/workflows/pipeline.yml"] },
      /protected path/,
    ],
    ["round 3", { round: MAX_ROUNDS + 1 }, /round 3: only 2 rounds/],
    ["an unreadable round", { round: Number.NaN }, /round could not be read/],
    [
      "a round that already sent one",
      {
        markers: readMarkers({
          issueComments: [
            {
              author_association: "OWNER",
              created_at: "t",
              body: respondMarker({ sha: SHA, round: 1 }),
            },
          ],
        }),
      },
      /already sent/,
    ],
    ["an unreadable dial", { gate: null }, /dial could not be read/],
    [
      "a refusal from the work gate",
      { gate: { dispatch: false, position: "halt", reason: "work-mode=halt" } },
      /work-mode=halt/,
    ],
  ];
  for (const [name, over, why] of cases) {
    it(`refuses ${name}`, () => {
      const verdict = route(over);
      expect(verdict.dispatch).toBe(false);
      expect(verdict.reason).toMatch(why);
    });
  }

  it("refuses when the PR could not be read", () => {
    expect(routeRespond({ importantOpen: 1 }).reason).toMatch(/could not be read/);
  });
});

describe("the one yes", () => {
  it("sends a session for a session's PR in rounds 1 and 2, with the round's marker", () => {
    expect(route()).toEqual({
      dispatch: true,
      reason: "2 Important finding(s) open in round 1",
      marker: respondMarker({ sha: SHA, round: 1 }),
    });
    expect(route({ round: 2 }).dispatch).toBe(true);
  });

  it("sends one for a lane's own PR too: the thread is the lane's to answer", () => {
    expect(
      route({
        pr: pr({ author_association: "NONE", user: { login: "skynet-bot[bot]", type: "Bot" } }),
      }).dispatch,
    ).toBe(true);
  });

  it("leaves one line on the PR that carries the round's marker", () => {
    const line = respondLine(route(), "---\n_Generated by [Claude Code](https://claude.ai/code)_");
    expect(line).toContain(respondMarker({ sha: SHA, round: 1 }));
    expect(line).toContain("2 Important finding(s) open in round 1");
  });
});

describe("gathering one PR", () => {
  it("reads the PR, both names of a renamed file, the markers, and the gate", () => {
    const api = fakeApi({
      "pulls/6870": pr(),
      "pulls/6870/files": [{ filename: "src/b.ts", previous_filename: ".github/workflows/x.yml" }],
      "pulls/6870/reviews": [],
      "pulls/6870/comments": [],
      "issues/6870/comments": [],
    });
    const got = gatherRespond(6870, { api, gate: () => OPEN_GATE, rules: [] });
    expect(got.files).toEqual(["src/b.ts", ".github/workflows/x.yml"]);
    expect(got.gate).toEqual(OPEN_GATE);
  });

  it("turns a gate that throws into a refusal that says why", () => {
    const api = fakeApi({
      "pulls/1": pr(),
      "pulls/1/files": [],
      "pulls/1/reviews": [],
      "pulls/1/comments": [],
      "issues/1/comments": [],
    });
    const got = gatherRespond(1, {
      api,
      gate: () => {
        throw new Error("breaker unreadable");
      },
      rules: [],
    });
    expect(got.gate).toMatchObject({ dispatch: false, reason: "refused: breaker unreadable" });
  });
});
