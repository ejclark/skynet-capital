// The org chart — who talks to whom, generated from the seat registry (docs/agents/seats.json).
//
// WHY THIS EXISTS. Eric, 2026-11-07: "The friction with AI that we've worked to optimize boils down
// to improving communication. AI can 'solve' conways Law to autonomously evolve our communication
// strucutre; 'reverse conways law'… the digram that would be most helpful is an outline of our
// agentic systems, how they all interact, and more effectively enhance. This is also a valuable
// artifact to compact context for our agentic workflows. Think of this diagram as a company 'org
// chart'. Include human users in the diagram." Conway's law says a system copies the communication
// structure that builds it, so the chart is the benchmark: its edges carry measured friction, and
// changing an edge on purpose is how the system gets the shape we want.
//
// WHY GENERATED. A hand-drawn org chart goes stale the week a lane is added, which is how the
// architecture storybook came to be generated too (scripts/architecture-pages.mjs). The registry is
// also #6886's seat registry (slice 1): one row per seat, so the board's Role field, this page and
// any workflow that wants compact context all read one file.
//
//   node scripts/org-chart.mjs           # rewrite docs/architecture/org-chart.md from the registry
//   node scripts/org-chart.mjs --check   # exit 1 if the page on disk differs from the render
//
// Enforced by tests/arch/org-chart.spec.ts, which also checks every code root exists and every
// agent, skill, workflow, lane prompt and output style is covered by a seat. Dependency-free.

import { readFileSync, writeFileSync } from "node:fs";

export const SOURCE = "docs/agents/seats.json";
export const PAGE = "docs/architecture/org-chart.md";

/** What starts a seat, in words. `none` is the one the page calls out. */
export const INVOKERS = {
  event: "a GitHub event",
  schedule: "a schedule",
  lane: "another lane",
  session: "a session",
  member: "a member",
  eric: "Eric",
  self: "themselves",
  none: "nothing",
};

const cell = (s) =>
  String(s ?? "")
    .replace(/\s*\n\s*/g, " ")
    .replace(/\|/g, "\\|")
    .trim();
const nodeId = (id) => id.replace(/[^A-Za-z0-9]/g, "_");
const shortName = (name) => name.split(" (")[0];

/** The picture: people and departments as nodes, the registry's links as labelled edges. */
function picture(reg) {
  const seatsIn = (dept) => reg.seats.filter((s) => s.department === dept).length;
  const node = (id) => {
    const person = reg.people.find((p) => p.id === id);
    if (person) return `${nodeId(id)}(["${person.label}"])`;
    const dept = reg.depts.find((d) => d.id === id);
    if (dept) return `${nodeId(id)}["${dept.name} · ${seatsIn(id)} seats"]`;
    const seat = reg.seats.find((s) => s.id === id);
    if (seat) return `${nodeId(id)}["${shortName(seat.name)}"]`;
    throw new Error(`link endpoint ${id} is not a person, department or seat`);
  };
  const ids = [...new Set(reg.links.flatMap((l) => [l.from, l.to]))];
  const lines = ["```mermaid", "flowchart TD"];
  for (const id of ids) lines.push(`  ${node(id)}`);
  // Live edges move and paths with no push or access yet stay still (docs/PICTURES.md → the delta grammar).
  const live = [];
  reg.links.forEach((l, i) => {
    if (l.weak) {
      lines.push(`  ${nodeId(l.from)} -.->|"${l.label}"| ${nodeId(l.to)}`);
    } else {
      live.push(`e${i}`);
      lines.push(`  ${nodeId(l.from)} e${i}@-->|"${l.label}"| ${nodeId(l.to)}`);
    }
  });
  for (const e of live) lines.push(`  ${e}@{ animate: true }`);
  lines.push("```");
  return lines.join("\n");
}

/** One table per department, every seat a row; code roots last, for the agents that read raw. */
function departments(reg) {
  return reg.depts
    .map((d) => {
      const rows = reg.seats
        .filter((s) => s.department === d.id)
        .map(
          (s) =>
            `| ${cell(s.name)} | ${cell(s.job)} | ${cell(s.wakesOn)} | ${cell(s.speaksOn)} | ${cell(s.status)} | ${s.codeRoots.map((r) => `\`${r}\``).join(" ")} |`,
        );
      return [
        `### ${d.name}`,
        "",
        `${d.job}.`,
        "",
        "| Seat | Job | Wakes on | Speaks on | Status | Code roots |",
        "|---|---|---|---|---|---|",
        ...rows,
      ].join("\n");
    })
    .join("\n\n");
}

export function render(reg) {
  // People start themselves; the gap lists are about seats a session or a schedule could start.
  const machine = reg.seats.filter((s) => s.kind !== "human");
  const nothing = machine.filter((s) => s.invoker === "none");
  const ericOnly = machine.filter((s) => s.invoker === "eric");
  const stations = reg.seats.filter((s) => s.station);
  const below = reg.seats.filter(
    (s) => !s.station && ["build", "quality", "staff", "platform"].includes(s.department),
  );
  return `<!-- GENERATED by scripts/org-chart.mjs from ${SOURCE}. Edit the registry, not this page. -->
# The org chart — who talks to whom

Every seat that does work here, human or agent, and the channels between them, as of ${reg.asOf}.
It is two things at once:

- **The benchmark for reverse Conway** (Eric, 2026-11-07). A system copies the communication
  structure that builds it. So the edges below carry their measured friction, and changing an edge
  on purpose is how the system gets the shape we want.
- **Compact context for a workflow.** One read gives a session or an agent every seat's job, what
  wakes it, what it says and where its code lives, without re-deriving the system by grep.

${picture(reg)}

_Caption — the departments and people, from \`${SOURCE}\`; dotted edges are paths with no push or no access yet._

## Where the talk breaks down

The friction census (2026-11-07): each row is a communication edge with a breakdown, measured where
we could, the change that would give the shape we want, and where that change is tracked.

| Edge | Channel | What goes wrong | Measured | The change | Tracked in |
|---|---|---|---|---|---|
${reg.friction.map((f) => `| ${cell(f.edge)} | ${cell(f.channel)} | ${cell(f.what)} | ${cell(f.number)} (${cell(f.cite)}) | ${cell(f.change)} | ${cell(f.tracked)} |`).join("\n")}

**The shape today is a star.** Every decision a lane cannot settle ends at Eric, and most lane seats
speak through one App identity and one router (the board and member filings use separate tokens).
He gets the digest, newsletter and ask-card pushes; members get no push about their asks. Nearly all
feedback is filed by sessions under his account, and no other member has filed from the app since
2026-08-28.

**The shape we are steering toward:**

${reg.target.map((t) => `- ${t}`).join("\n")}

## Seats with no reporting line

- **Nothing starts these (${nothing.length}):** ${nothing.map((s) => s.name).join(" · ")}. Each needs an invoker, or the bench (\`/charter\` sunset mode).
- **Only Eric starts these (${ericOnly.length}):** ${ericOnly.map((s) => shortName(s.name)).join(" · ")}. Each is a phrase he has to remember; a schedule or an event would take it off him.

## The crew on the deck

How the chart reads to a member, through the landing page (#7018) and the campaign (#6948). Only
seats a member deals with get a station, named by its job. The rest work below decks: a member
feels them only as honest timing on their own ask ("queued behind 2 builds"), never as a screen
(Eric, 2026-11-07, #6948: "if we have to explain implementation details, were doing something wrong").

| Station | Seat behind it |
|---|---|
${stations.map((s) => `| ${cell(s.station)} | ${cell(s.name)} |`).join("\n")}

Below decks: ${below.length} seats, every one in Builders, Quality, Chief of staff and Platform. A
member sees their own ask's status in plain words, never the lanes.

## Departments

${departments(reg)}

## Changing this page

Edit \`${SOURCE}\`, then run \`node scripts/org-chart.mjs\`. \`tests/arch/org-chart.spec.ts\` fails when
the page drifts from the registry, a code root is gone, or an agent, skill, workflow, lane prompt or
output style has no seat. What starts a seat (\`invoker\`): ${Object.entries(INVOKERS)
    .map(([k, v]) => `\`${k}\` ${v}`)
    .join(" · ")}.
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const reg = JSON.parse(readFileSync(SOURCE, "utf8"));
  const page = render(reg);
  if (process.argv.includes("--check")) {
    const disk = readFileSync(PAGE, "utf8");
    if (disk !== page) {
      console.error(`${PAGE} differs from the render of ${SOURCE}: run node scripts/org-chart.mjs`);
      process.exit(1);
    }
    console.log(`org chart matches ${SOURCE}`);
  } else {
    writeFileSync(PAGE, page);
    console.log(`wrote ${PAGE} (${reg.seats.length} seats, ${reg.friction.length} friction rows)`);
  }
}
