#!/usr/bin/env node
// loop-check.mjs — the learning-loop registry checks itself (2026-10-18 loop census).
//
//   node scripts/loop-check.mjs            # print what is due and what each check says
//   node scripts/loop-check.mjs --post     # post each unposted due check to the tracker issue
//   node scripts/loop-check.mjs --registry <file>   # read another copy of the registry (a dry run)
//
// WHY. `docs/process/LEARNING-LOOP.md` → "Loops running now" holds the system's own experiments
// about itself, each with a dated Next check. Every check depended on someone remembering: on
// 2026-10-18 three were overdue (10-10, 10-15, 10-17), none had surfaced in seven daily digests (the
// digest's stored prompt never runs `doctrine-scan --due`), and the owning issues of 14 of the 16
// dated rows were closed, so there was nowhere to report. Eric, the same day: "we should be looking
// for ways to automate away Manual checks; that's the only way to scale."
//
// WHAT IT AUTOMATES — sense and the measuring half of act. A running row whose Next check has
// arrived gets ONE comment on the tracker issue per date, deduped by a hidden marker. When the row's
// question names `npm run <x>`, the comment carries that command's output beside the row's stated
// falsifier, so the number and the line it is judged against sit together. Rows checked by hand get
// a "due" line naming what settles them.
//
// WHAT IT NEVER DOES — decide. Moving the row's date, or ending the loop, stays a judgment against a
// prose falsifier, not a mechanical comparison. The push tick calls `--post` from
// `scripts/moneypenny/index.mjs --audit`; a failure here never fails the audit.
//
// THE DECIDE STEP, ROUTED (#5724 retro, 2026-10-26). Posting turned out to be half a loop: the
// tracker is a standing log nobody reads, and by 10-26 five posted checks sat 4–16 days unmoved.
// So a check still unmoved UNMOVED_DAYS after its post becomes ONE small `feedback` issue (opened,
// or its body updated; a marker finds it) listing those rows, filed `ready` under the small-ask rule
// (docs/ISSUES.md → Who may flip it: a session's own small, well-scoped filing at capture). The
// build lane then makes the call each row asks for. Never `needs-eric`: a verdict against a stated
// falsifier is lane work, and a loop whose owning issue is open is never ended by it.
//
// Pure core (`dueChecks`, `checkBody`, `commandOf`) + thin I/O shell, like doctrine-scan.mjs.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buriedDates, overdueLoops, parseLoopList } from "./loop-list-decide.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LIST = join(ROOT, "docs", "process", "LEARNING-LOOP.md");
/** The line in LEARNING-LOOP.md naming the tracker issue — the config lives beside the table. */
const TRACKER_LINE = /\*\*Check results post to:\*\*\s*#(\d+)/;
const RUN_TIMEOUT_MS = 90_000;
const OUTPUT_CHARS = 3_000;
const FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_";
/** Days a posted check may sit with its row unmoved before the decide step files it. */
export const UNMOVED_DAYS = 3;
/** The hidden marker the one decide-step issue carries — found again by it, never by title. */
export const UNMOVED_MARKER = "<!-- loop-check:unmoved -->";

const slugOf = (loop) =>
  loop
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

/** The hidden marker one (loop, date) check is posted under — the dedupe key. */
export const markerOf = (loop, date) => `<!-- loop-check:${slugOf(loop)}:${date} -->`;

/** The `npm run <x>` a row's question names, or null when the check is done by hand. */
export function commandOf(question) {
  const m = /npm run ([a-z0-9:_-]+)/i.exec(String(question ?? ""));
  return m ? m[1] : null;
}

/** The tracker issue number from the registry's own text, or null when it names none. */
export function trackerOf(md) {
  const m = TRACKER_LINE.exec(String(md ?? ""));
  return m ? Number(m[1]) : null;
}

/** The due checks not yet posted: the registry's overdue rows minus those whose marker exists. */
export function dueChecks({ today, rows, posted = [] }) {
  const seen = posted.join("\n");
  return overdueLoops({ today, rows })
    .map((r) => ({ ...r, command: commandOf(r.question), marker: markerOf(r.loop, r.nextCheck) }))
    .filter((r) => !seen.includes(r.marker));
}

const dayNumber = (date) => Date.parse(`${date}T00:00:00Z`) / 86_400_000;

/**
 * The checks nobody settled: a running row whose date has come, whose check for THAT date was
 * posted at least `days` ago, and which still carries the same date. Moving the date or ending the
 * loop drops it on the next tick, so the list is always the current debt, never a history.
 * `comments` are the tracker's comments, `{ body, createdAt, url }`.
 */
export function unmovedChecks({ today, rows, comments = [], days = UNMOVED_DAYS }) {
  return overdueLoops({ today, rows }).flatMap((r) => {
    const marker = markerOf(r.loop, r.nextCheck);
    const post = comments.find((c) => String(c.body ?? "").includes(marker));
    if (!post) return [];
    const postedOn = String(post.createdAt).slice(0, 10);
    const waited = dayNumber(today) - dayNumber(postedOn);
    return waited >= days ? [{ ...r, postedOn, waited, url: post.url ?? null }] : [];
  });
}

/** The decide-step issue: title, labels and a capsule body that passes `issue-lint`. */
export function unmovedIssue({ checks, tracker }) {
  const n = checks.length;
  const rows = checks.map(
    (c) =>
      `| ${c.loop} | ${c.nextCheck} | ${c.url ? `[${c.postedOn}](${c.url})` : c.postedOn} · ${c.waited} days | ${c.issue || "—"} |`,
  );
  return {
    title: `Settle ${n} learning-loop check${n === 1 ? "" : "s"} that posted and then sat unmoved`,
    labels: ["feedback", "ready"],
    body: [
      UNMOVED_MARKER,
      `**Settle ${n} row${n === 1 ? "" : "s"} of the learning-loop registry: each check posted to #${tracker} and its Next check date has not moved since.**`,
      "",
      "| | |",
      "|---|---|",
      "| **Type** | self-learning · learning loops |",
      "| **Surface** | `docs/process/LEARNING-LOOP.md` → *Loops running now* |",
      "| **Size** | S |",
      `| **Source** | \`scripts/loop-check.mjs\` on the push tick: unmoved ${UNMOVED_DAYS}+ days after posting |`,
      "",
      `- The posted check on #${tracker} holds each row's output and the falsifier it is judged against.`,
      "- For each row, record the verdict in its Next check cell, then move the date or end the loop.",
      "- A loop whose owning issue is still open keeps running: record the verdict and move the date.",
      "",
      "Picture: waived — a list of registry rows; the posted checks are the evidence.",
      "",
      "<details><summary><strong>The rows and the criteria</strong></summary>",
      "",
      "| Loop | Next check | Posted | Owning issue |",
      "|---|---|---|---|",
      ...rows,
      "",
      "### Acceptance criteria (EARS)",
      "",
      "- WHEN the fixing PR merges, each row above SHALL lead its Next check cell with a later date, or carry an ended State (`closed` · `killed` · `pivoted` · `replaced`).",
      "- The PR SHALL record each verdict against the row's falsifier, quoting the posted output where the check ran a command.",
      "- WHILE a row's owning issue is open, the PR SHALL NOT end that loop.",
      "",
      "</details>",
      "",
      FOOTER,
    ].join("\n"),
  };
}

/** One check's comment: the loop, its question, its falsifier, and what the command printed. */
export function checkBody(check, result) {
  const head = `**Loop check — ${check.loop}** (Next check ${check.nextCheck}${check.issue ? ` · owning ${check.issue}` : ""})`;
  const what = result
    ? result.ok
      ? ["`npm run " + check.command + "`:", "", "```", result.output, "```"]
      : [`\`npm run ${check.command}\` did not finish: ${result.output}. Run it by hand.`]
    : ["Checked by hand — nothing names a command to run."];
  return [
    head,
    "",
    `> ${check.question}`,
    "",
    `**Judged against:** ${check.nextCheckText || check.nextCheck}`,
    "",
    ...what,
    "",
    "Settle it in `docs/process/LEARNING-LOOP.md`: move the row's Next check, or end the loop.",
    "",
    check.marker,
    FOOTER,
  ].join("\n");
}

function run(command) {
  try {
    const out = execFileSync("npm", ["run", "-s", command], {
      cwd: ROOT,
      encoding: "utf8",
      timeout: RUN_TIMEOUT_MS,
      stdio: ["ignore", "pipe", "pipe"],
    });
    const text = out.trim();
    return {
      ok: true,
      output: text.length > OUTPUT_CHARS ? `${text.slice(0, OUTPUT_CHARS)}\n…(truncated)` : text,
    };
  } catch (err) {
    const why =
      err?.code === "ETIMEDOUT" || err?.signal === "SIGTERM"
        ? `timed out after ${RUN_TIMEOUT_MS / 1000}s`
        : `exit ${err?.status ?? "?"}`;
    return { ok: false, output: why };
  }
}

const gh = (args) => execFileSync("gh", args, { cwd: ROOT, encoding: "utf8" });

/** The I/O shell. `post` false prints; true posts unposted due checks to the tracker. */
/** Every page of a REST list as one array (`--slurp` keeps paginated JSON parseable). */
const ghAll = (path) => JSON.parse(gh(["api", path, "--paginate", "--slurp"])).flat();

/** Open the one decide-step issue, or bring its body up to date. Returns its number, or null. */
function fileUnmoved(issue) {
  const open = ghAll("repos/{owner}/{repo}/issues?state=open&per_page=100").find((i) =>
    String(i.body ?? "").includes(UNMOVED_MARKER),
  );
  if (open) {
    if (open.body.trim() !== issue.body.trim()) {
      gh([
        "api",
        `repos/{owner}/{repo}/issues/${open.number}`,
        "-X",
        "PATCH",
        "-f",
        `title=${issue.title}`,
        "-f",
        `body=${issue.body}`,
      ]);
    }
    return open.number;
  }
  const url = gh([
    "issue",
    "create",
    "--title",
    issue.title,
    "--body",
    issue.body,
    "--label",
    issue.labels.join(","),
  ]);
  return Number(url.match(/\/issues\/(\d+)/)?.[1]) || null;
}

/** The I/O shell. `post` false prints; true posts unposted due checks to the tracker and routes
 *  the unmoved ones to the decide-step issue. `registry` reads another copy of the list. */
export function loopCheck({
  post = false,
  today = new Date().toISOString().slice(0, 10),
  registry = LIST,
} = {}) {
  const md = readFileSync(registry, "utf8");
  const rows = parseLoopList(md) ?? [];
  const tracker = trackerOf(md);
  // Read the tracker even on a dry run when a token is at hand: the unmoved list needs post dates.
  let comments = [];
  if (tracker && (post || process.env.GH_TOKEN || process.env.GITHUB_TOKEN)) {
    comments = ghAll(`repos/{owner}/{repo}/issues/${tracker}/comments?per_page=100`).map((c) => ({
      body: c.body,
      createdAt: c.created_at,
      url: c.html_url,
    }));
  }
  const due = dueChecks({ today, rows, posted: comments.map((c) => c.body) });
  for (const check of due) {
    const body = checkBody(check, check.command ? run(check.command) : null);
    if (post && tracker) gh(["issue", "comment", String(tracker), "--body", body]);
    else console.log(`${body}\n`);
  }
  for (const b of buriedDates(rows)) {
    console.log(
      `::warning::loop-check — "${b.loop}" names ${b.date} but its Next check cell does not lead with it, so it is never checked`,
    );
  }
  const unmoved = unmovedChecks({ today, rows, comments });
  if (unmoved.length) {
    const issue = unmovedIssue({ checks: unmoved, tracker });
    if (post) {
      const n = fileUnmoved(issue);
      console.log(`loop-check: ${unmoved.length} unmoved check(s) routed to #${n ?? "?"}.`);
    } else {
      console.log(
        `loop-check: ${unmoved.length} unmoved check(s) would be filed:\n\n${issue.title}\n\n${issue.body}\n`,
      );
    }
  }
  return due.length;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const post = process.argv.includes("--post");
  const at = process.argv.indexOf("--registry");
  const n = loopCheck({
    post,
    ...(at > -1 ? { registry: process.argv[at + 1] } : {}),
  });
  console.log(`loop-check: ${n} due check(s) ${post ? "posted" : "listed"}.`);
}
