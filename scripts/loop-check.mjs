#!/usr/bin/env node
// loop-check.mjs — the learning-loop registry checks itself (2026-10-18 loop census).
//
//   node scripts/loop-check.mjs            # print what is due and what each check says
//   node scripts/loop-check.mjs --post     # post each unposted due check to the tracker issue
//
// WHY. `docs/process/LEARNING-LOOP.md` → "Loops running now" holds the system's own experiments
// about itself, each with a dated Next check. Every check depended on someone remembering: on
// 2026-10-18 three were overdue (10-10, 10-15, 10-17), none had surfaced in seven daily digests (the
// digest's stored prompt never runs `doctrine-scan --due`), and the owning issues of 14 of the 16
// dated rows were closed, so there was nowhere to report. Eric, the same day: "we should be looking
// for ways to automate away Manual checks; that's the only way to scale."
//
// WHAT IT AUTOMATES — sense and the measuring half of act. A running row whose Next check has
// arrived gets ONE comment on the tracker issue per date, deduped by a hidden marker. When the row's
// question names `npm run <x>`, the comment carries that command's output beside the row's stated
// falsifier, so the number and the line it is judged against sit together. Rows checked by hand get
// a "due" line naming what settles them.
//
// WHAT IT NEVER DOES — decide. Moving the row's date, or ending the loop, stays with the owner: the
// verdict is a judgment against a prose falsifier, not a mechanical comparison (yet). The push tick
// calls `--post` from `scripts/moneypenny/index.mjs --audit`; a failure here never fails the audit.
//
// Pure core (`dueChecks`, `checkBody`, `commandOf`) + thin I/O shell, like doctrine-scan.mjs.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { overdueLoops, parseLoopList } from "./loop-list-decide.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LIST = join(ROOT, "docs", "process", "LEARNING-LOOP.md");
/** The line in LEARNING-LOOP.md naming the tracker issue — the config lives beside the table. */
const TRACKER_LINE = /\*\*Check results post to:\*\*\s*#(\d+)/;
const RUN_TIMEOUT_MS = 90_000;
const OUTPUT_CHARS = 3_000;
const FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_";

const slugOf = (loop) =>
  loop
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

/** The hidden marker one (loop, date) check is posted under — the dedupe key. */
export const markerOf = (loop, date) => `<!-- loop-check:${slugOf(loop)}:${date} -->`;

/** The `npm run <x>` a row's question names, or null when the check is done by hand. */
export function commandOf(question) {
  const m = /npm run ([a-z0-9:_-]+)/i.exec(String(question ?? ""));
  return m ? m[1] : null;
}

/** The tracker issue number from the registry's own text, or null when it names none. */
export function trackerOf(md) {
  const m = TRACKER_LINE.exec(String(md ?? ""));
  return m ? Number(m[1]) : null;
}

/** The due checks not yet posted: the registry's overdue rows minus those whose marker exists. */
export function dueChecks({ today, rows, posted = [] }) {
  const seen = posted.join("\n");
  return overdueLoops({ today, rows })
    .map((r) => ({ ...r, command: commandOf(r.question), marker: markerOf(r.loop, r.nextCheck) }))
    .filter((r) => !seen.includes(r.marker));
}

/** One check's comment: the loop, its question, its falsifier, and what the command printed. */
export function checkBody(check, result) {
  const head = `**Loop check — ${check.loop}** (Next check ${check.nextCheck}${check.issue ? ` · owning ${check.issue}` : ""})`;
  const what = result
    ? result.ok
      ? ["`npm run " + check.command + "`:", "", "```", result.output, "```"]
      : [`\`npm run ${check.command}\` did not finish: ${result.output}. Run it by hand.`]
    : ["Checked by hand — nothing names a command to run."];
  return [
    head,
    "",
    `> ${check.question}`,
    "",
    `**Judged against:** ${check.nextCheckText || check.nextCheck}`,
    "",
    ...what,
    "",
    "Settle it in `docs/process/LEARNING-LOOP.md`: move the row's Next check, or end the loop.",
    "",
    check.marker,
    FOOTER,
  ].join("\n");
}

function run(command) {
  try {
    const out = execFileSync("npm", ["run", "-s", command], {
      cwd: ROOT,
      encoding: "utf8",
      timeout: RUN_TIMEOUT_MS,
      stdio: ["ignore", "pipe", "pipe"],
    });
    const text = out.trim();
    return {
      ok: true,
      output: text.length > OUTPUT_CHARS ? `${text.slice(0, OUTPUT_CHARS)}\n…(truncated)` : text,
    };
  } catch (err) {
    const why =
      err?.code === "ETIMEDOUT" || err?.signal === "SIGTERM"
        ? `timed out after ${RUN_TIMEOUT_MS / 1000}s`
        : `exit ${err?.status ?? "?"}`;
    return { ok: false, output: why };
  }
}

const gh = (args) => execFileSync("gh", args, { cwd: ROOT, encoding: "utf8" });

/** The I/O shell. `post` false prints; true posts unposted due checks to the tracker. */
export function loopCheck({ post = false, today = new Date().toISOString().slice(0, 10) } = {}) {
  const md = readFileSync(LIST, "utf8");
  const rows = parseLoopList(md) ?? [];
  const tracker = trackerOf(md);
  const posted =
    post && tracker
      ? JSON.parse(
          gh([
            "api",
            `repos/{owner}/{repo}/issues/${tracker}/comments?per_page=100`,
            "--paginate",
            "--jq",
            "[.[].body]",
          ]).replace(/\]\s*\[/g, ","),
        )
      : [];
  const due = dueChecks({ today, rows, posted });
  for (const check of due) {
    const body = checkBody(check, check.command ? run(check.command) : null);
    if (post && tracker) gh(["issue", "comment", String(tracker), "--body", body]);
    else console.log(`${body}\n`);
  }
  return due.length;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const post = process.argv.includes("--post");
  const n = loopCheck({ post });
  console.log(`loop-check: ${n} due check(s) ${post ? "posted" : "listed"}.`);
}
