#!/usr/bin/env node
// profile-scan: Eric's profile learns from every answer he gives (#8197 slice 2).
//
// Eric, 2026-11-23, on #8161: "I'm sure many aspects are off base, the key is the ability to capture
// datapoints and refine. Given enough iterations and time, systematic paths like that are
// guaranteed to overtake unorganized paths." docs/members/eric.md is the one home for what he likes
// and dislikes; docs/process/ALIGNMENT.md is the sensor. This closes the loop between them:
//
//   --misses [--route]  every ledger miss no profile line cites as `ALIGNMENT <date> · <ask id>`.
//                       --route opens or refreshes ONE ready feedback issue (found by MISSES_MARKER,
//                       never by title) that the build lane closes by editing the profile.
//   --due               the hypotheses whose check-by date has come, and the ledger's match share
//                       since the audit (the loop's own falsifier: above 70%, LEARNING-LOOP.md).
//   --validate          every hypothesis in eric.md, and every numbered one (`Hn`) in any member
//                       file, carries "Proves it wrong (check by YYYY-MM-DD)". A format check, never a
//                       time check, so it cannot turn an unrelated PR red. The spec runs it.
//   --check             the fitness contract misses-reach-profile's verdict, printed.
//
// The ask id is the ledger's ask cell up to its first ` · `, else its first `#N`, else the whole
// cell. A Score that says `no profile change: <why>` is skipped (a private or superseded miss).
// The citation is looked for in eric.md and READERS.md only: a cite anywhere else changed nothing a
// reader of his profile sees. The grace period runs from the row's own date, not from today.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { scoreOf, sectionRows } from "./alignment-graduation.mjs";
import { isMain } from "./is-main.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const FILES = {
  ledger: join(ROOT, "docs", "process", "ALIGNMENT.md"),
  profile: [join(ROOT, "docs", "members", "eric.md"), join(ROOT, "docs", "READERS.md")],
  members: join(ROOT, "docs", "members"),
};
export const GRACE_DAYS = 7;
/** The audit that wrote H1–H8; the loop's match share is read over rows dated after it. */
export const AUDIT_DATE = "2026-11-23";
export const MATCH_BAR = 0.7;
export const MISSES_MARKER = "<!-- profile-scan:misses -->";
const FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_";
const DAY_MS = 86_400_000;
const DAY = /^\d{4}-\d{2}-\d{2}$/;

const flat = (s) => String(s ?? "").replace(/\s+/g, " ");

/** Every `_hypothesis …_` in a markdown file, with its id, dates and whether it can be checked. */
export function parseHypotheses(md, file = "") {
  const out = [];
  for (const m of String(md ?? "").matchAll(
    /_hypothesis\b((?:(?!_hypothesis\b)[\s\S])*?)_(?=\s|$)/g,
  )) {
    const text = flat(m[1]).trim();
    out.push({
      file,
      id: text.match(/^(H\d+)\b/)?.[1] ?? null,
      written: text.match(/\d{4}-\d{2}-\d{2}/)?.[0] ?? null,
      checkBy: text.match(/check by (\d{4}-\d{2}-\d{2})/i)?.[1] ?? null,
      falsifier: /proves it wrong/i.test(text),
      text,
    });
  }
  return out;
}

/** The hypotheses the grammar binds that break it: all of eric.md's, and any numbered one. */
export function invalidHypotheses(hyps, home = "eric.md") {
  return hyps.filter((h) => (h.file.endsWith(home) || h.id) && !(h.falsifier && h.checkBy && h.id));
}

/** Hypotheses whose check-by date is today or earlier. */
export const dueHypotheses = (hyps, today) => hyps.filter((h) => h.checkBy && h.checkBy <= today);

/** The ask id a citation names: before the first ` · `, else the first `#N`, else the cell. */
export function askIdOf(ask) {
  const s = flat(ask).trim();
  if (s.includes(" · ")) return s.slice(0, s.indexOf(" · ")).trim();
  return s.match(/#\d+/)?.[0] ?? s;
}

/** Every scored ledger row: `{ date, ask, askId, cite, score, raw, skip }`. */
export function ledgerRows(ledgerMd) {
  return sectionRows(ledgerMd, "Ledger")
    .filter((c) => c.length >= 6 && DAY.test(c[0]))
    .map((c) => {
      const askId = askIdOf(c[2]);
      return {
        date: c[0],
        ask: c[2],
        predicted: c[3],
        given: c[4],
        askId,
        cite: `ALIGNMENT ${c[0]} · ${askId}`,
        score: scoreOf(c[5]),
        raw: c[5],
        skip: /no profile change:/i.test(c[5]),
      };
    })
    .map((r, _, all) =>
      // An id shared by two asks on one day would let one line clear both: cite the whole cell.
      // That covers `#N · <question>` too, answer-readback's row format for a multi-question card
      // (#8342); a row alone on its day keeps its short cite, so existing profile cites still hold.
      all.some((o) => o !== r && o.cite === r.cite)
        ? { ...r, askId: flat(r.ask).trim(), cite: `ALIGNMENT ${r.date} · ${flat(r.ask).trim()}` }
        : r,
    );
}

/** The misses still owed a profile line: a `miss…` Score, not marked `no profile change:`. */
export const missRows = (rows) => rows.filter((r) => r.score === "miss" && !r.skip);

/** Whether `text` cites `cite` as a whole token: "#7018 round 1" never counts for "round 1 Q1". */
export function cites(text, cite) {
  const hay = flat(text);
  let at = hay.indexOf(cite);
  while (at !== -1) {
    // The id ends at punctuation or the end; a space then a letter or digit is more of an id.
    if (/^(?:$|[^A-Za-z0-9 ]| (?![A-Za-z0-9]))/.test(hay.slice(at + cite.length))) return true;
    at = hay.indexOf(cite, at + 1);
  }
  return false;
}

/** Misses no profile text cites, with their age in days from the row's own date. */
export function uncitedMisses(rows, profileTexts, today) {
  const texts = profileTexts.map(flat);
  const todayMs = Date.parse(`${today}T00:00:00Z`);
  return missRows(rows)
    .filter((r) => !texts.some((t) => cites(t, r.cite)))
    .map((r) => ({
      ...r,
      age: Math.floor((todayMs - Date.parse(`${r.date}T00:00:00Z`)) / DAY_MS),
    }));
}

/** match / (match + miss) over rows dated after `since`, or null with none scored. */
export function matchShare(rows, since = AUDIT_DATE) {
  const scored = rows.filter((r) => r.date > since && (r.score === "match" || r.score === "miss"));
  const match = scored.filter((r) => r.score === "match").length;
  return { match, scored: scored.length, share: scored.length ? match / scored.length : null };
}

/** The fitness verdict: fail on any uncited miss older than the grace period. */
export function judge({ ledgerMd, profileTexts, today, graceDays = GRACE_DAYS }) {
  const late = uncitedMisses(ledgerRows(ledgerMd), profileTexts, today).filter(
    (r) => r.age > graceDays,
  );
  return late.length
    ? {
        status: "fail",
        detail: `${late.length} misses older than ${graceDays} days with no cited profile line: ${late.map((r) => `${r.date} · ${r.askId}`).join(", ")}`,
      }
    : {
        status: "pass",
        detail: `every miss older than ${graceDays} days has a cited profile line`,
      };
}

const cell = (s) => flat(s).replace(/\|/g, "\\|");

/** The one routed issue: title, labels and a capsule body. */
export function missesIssue(misses) {
  const n = misses.length;
  const rows = misses.map(
    (r) =>
      `| \`${r.cite}\` | ${cell(r.predicted)} | ${cell(r.given)} | ${r.predicted.match(/eric\.md (H\d+)/)?.[1] ?? "—"} |`,
  );
  return {
    title: `Change Eric's profile for ${n} overturned prediction${n === 1 ? "" : "s"}`,
    labels: ["feedback", "ready"],
    body: [
      MISSES_MARKER,
      `**Edit \`docs/members/eric.md\` for ${n} prediction${n === 1 ? "" : "s"} Eric overturned, citing each.**`,
      "",
      "| | |",
      "|---|---|",
      "| **Type** | self-learning · his profile |",
      "| **Surface** | `docs/members/eric.md` (a communication miss: `docs/READERS.md`) |",
      "| **Size** | S |",
      "| **Source** | `scripts/profile-scan.mjs --misses --route`, daily loops Routine step 5 (#8197) |",
      "",
      "- Each row is a ledger miss no profile line cites yet; the fitness check fails at 7 days.",
      "- Quote his words with date and source, or flip or delete the hypothesis the prediction leaned on.",
      "- Cite the row exactly as the first column; a private miss gets `no profile change: private` instead.",
      "",
      "Picture: waived — a list of ledger rows; the ledger holds the evidence.",
      "",
      "<details><summary><strong>The misses and the criteria</strong></summary>",
      "",
      "| Cite as | Predicted | His answer | Line it leaned on |",
      "|---|---|---|---|",
      ...rows,
      "",
      "### Acceptance criteria (EARS)",
      "",
      "- WHEN the fixing PR merges, `node scripts/profile-scan.mjs --misses` SHALL list none of the rows above.",
      "- Each new line SHALL quote his words with date and source, or be a hypothesis with a check-by date.",
      "- No line SHALL name a member, or add anything about family, money, hobbies or health.",
      "",
      "</details>",
      "",
      FOOTER,
    ].join("\n"),
  };
}

const gh = (args) => execFileSync("gh", args, { cwd: ROOT, encoding: "utf8" });

/** Open the one misses issue, or refresh its body. Returns its number, or null. */
function route(issue) {
  const open = JSON.parse(
    gh(["api", "repos/{owner}/{repo}/issues?state=open&per_page=100", "--paginate", "--slurp"]),
  )
    .flat()
    .find((i) => String(i.body ?? "").includes(MISSES_MARKER));
  if (open) {
    if (open.body.trim() !== issue.body.trim()) {
      const args = ["api", `repos/{owner}/{repo}/issues/${open.number}`, "-X", "PATCH"];
      gh([...args, "-f", `title=${issue.title}`, "-f", `body=${issue.body}`]);
    }
    // A lane that dropped `ready` after a failed build would leave the misses to age out unseen.
    gh(["issue", "edit", String(open.number), "--add-label", issue.labels.join(",")]);
    return open.number;
  }
  const url = gh([
    "issue",
    "create",
    "--title",
    issue.title,
    "--body",
    issue.body,
    "--label",
    issue.labels.join(","),
  ]);
  return Number(url.match(/\/issues\/(\d+)/)?.[1]) || null;
}

const read = (f) => readFileSync(f, "utf8");

/** Every member file's hypotheses. */
export function memberHypotheses(dir = FILES.members) {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .flatMap((f) => parseHypotheses(read(join(dir, f)), f));
}

function main(argv) {
  const today =
    argv.find((a) => a.startsWith("--today="))?.slice(8) ?? new Date().toISOString().slice(0, 10);
  const ledgerMd = read(FILES.ledger);
  const profileTexts = FILES.profile.map(read);
  if (argv.includes("--validate")) {
    const bad = invalidHypotheses(memberHypotheses());
    for (const h of bad)
      console.log(`✗ ${h.file}: ${h.id ?? "unnumbered"} — ${h.text.slice(0, 80)}…`);
    console.log(
      bad.length
        ? `profile-scan: ${bad.length} hypotheses break the grammar`
        : "profile-scan: every hypothesis carries a falsifier and a check-by date",
    );
    return bad.length ? 1 : 0;
  }
  if (argv.includes("--check")) {
    const v = judge({ ledgerMd, profileTexts, today });
    console.log(`misses-reach-profile: ${v.status} — ${v.detail}`);
    return v.status === "pass" ? 0 : 1;
  }
  if (argv.includes("--due")) {
    const due = dueHypotheses(parseHypotheses(profileTexts[0], "eric.md"), today);
    const s = matchShare(ledgerRows(ledgerMd));
    console.log(due.length ? `${due.length} hypotheses due:` : "no hypothesis is due");
    for (const h of due) console.log(`- ${h.id} (check by ${h.checkBy}): ${h.text.slice(0, 100)}…`);
    const share =
      s.share === null
        ? "none scored yet"
        : `${Math.round(s.share * 100)}% (${s.match} of ${s.scored})`;
    console.log(
      `match share after ${AUDIT_DATE}: ${share}; the loop is wrong at ${MATCH_BAR * 100}% or lower with 15+ rows`,
    );
    return 0;
  }
  if (argv.includes("--misses")) {
    const misses = uncitedMisses(ledgerRows(ledgerMd), profileTexts, today);
    for (const r of misses) console.log(`- ${r.cite} (${r.age} days)`);
    if (!misses.length) {
      console.log("profile clean");
      return 0;
    }
    if (argv.includes("--route"))
      console.log(`profile routed ${misses.length} → #${route(missesIssue(misses))}`);
    else console.log(`${misses.length} uncited; --route files them as one ready issue`);
    return 0;
  }
  console.log(
    "usage: profile-scan.mjs --misses [--route] | --due | --validate | --check [--today=YYYY-MM-DD]",
  );
  return 2;
}

if (isMain(import.meta.url)) process.exitCode = main(process.argv.slice(2));
