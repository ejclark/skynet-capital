// The instruction-file scope: the files every session and lane reads as instructions, defined once.
//
// WHY one module: two copies of a scope drift apart the same way two copies of a rule do, and rule
// drift is what the eyes importing this exist to catch (#5318). Importers:
// scripts/instruction-drift-scan.mjs (the semantic chore's item list). scripts/doc-rot-scan.mjs is
// the second importer once #5318 slice 1 widens it from top-level docs to this same surface.
//
// In: CLAUDE.md and README.md at the root, .claude/**/*.md, .github/prompts/*.md, the .github pull-
// request and issue templates, docs/**/*.md. Out: the ledgers and snapshots that describe their own
// moment (research, digests, journeys, vendored docs, legacy plans, LESSONS.md, IDEAS.md). They rot
// honestly, and a reader "fixing" them would rewrite history. A TEMPLATE.md or README.md inside a
// ledger folder stays in: sessions write new entries from it, so it is an instruction, not a record.
//
// Do-not-edit is a second, narrower question, answered on its own (`doNotEditReason`): files that
// are instructions to read but never to hand-edit, because a generator writes them, a lint checks
// quotes against them, or they are append-only records. A reader that only reads (doc-rot's dead
// references) may take them; a reader that rewrites (the instruction-drift chore) leaves them out.
//
// Pure: a caller hands in the path list (`git ls-files`, `git ls-tree -r <commit>`, a fixture), so
// one definition serves a live checkout, a historical commit and a spec alike.

/** Ledgers and snapshots: a trailing `/` is a directory prefix, anything else an exact path. */
const LEDGERS = [
  "docs/research/",
  "docs/digests/",
  "docs/JOURNEYS/",
  "docs/vendor/",
  "docs/plans/",
  "docs/LESSONS.md",
  "docs/IDEAS.md",
];
/** Inside a ledger folder, the files new entries are written from. */
const LEDGER_INSTRUCTIONS = /\/(TEMPLATE|README)\.md$/;

const ROOT_FILES = new Set(["CLAUDE.md", "README.md"]);
const CLAUDE_DOC = /^\.claude\/.+\.md$/;
const LANE_PROMPT = /^\.github\/prompts\/[^/]+\.md$/;
const DOC = /^docs\/.+\.md$/;
// GitHub reads these names case-insensitively. The ISSUE_TEMPLATE chooser's config.yml is settings
// (blank issues, contact links), not a template, so it stays out.
const TEMPLATE =
  /^\.github\/(pull_request_template\.md|PULL_REQUEST_TEMPLATE\/[^/]+\.md|ISSUE_TEMPLATE\/[^/]+\.(md|ya?ml))$/i;
const TEMPLATE_CONFIG = /^\.github\/ISSUE_TEMPLATE\/config\.ya?ml$/i;

/** Instruction files no reader may hand-edit, each with where its text really comes from. */
const DO_NOT_EDIT = [
  {
    test: /^docs\/architecture\/[^/]+\.md$/,
    why: "generated by scripts/architecture-pages.mjs from docs/architecture/source/ — tests/arch/architecture-pages.spec.ts fails a hand edit",
  },
  {
    test: /^docs\/STRUCTURE-graph\.md$/,
    why: "generated by `npm run graph:refresh`",
  },
  {
    test: /^docs\/members\/(coverage|maps|friction-ledger)\.md$/,
    why: "written by the crawl scripts (scripts/crawl/) — re-run them instead",
  },
  {
    test: /^docs\/members\/study\/[^/]+\/readout[^/]*\.md$/,
    why: "written by scripts/study/readout.mjs",
  },
  {
    test: /^docs\/design\/eric-feedback\/[^/]+\.md$/,
    why: "Eric's words banked verbatim — scripts/redesign/lint.mjs checks quotes against them",
  },
  {
    test: /^docs\/adr\/(?!0000-)\d{4}-[^/]+\.md$/,
    why: "an ADR is append-only history (docs/adr/README.md) — a later record supersedes it",
  },
];

const isLedger = (path) =>
  !LEDGER_INSTRUCTIONS.test(path) &&
  LEDGERS.some((entry) => (entry.endsWith("/") ? path.startsWith(entry) : path === entry));

/** True when a repo-relative POSIX path is an instruction file. */
export function isInstructionFile(path) {
  if (isLedger(path)) return false;
  if (ROOT_FILES.has(path)) return true;
  if (TEMPLATE_CONFIG.test(path)) return false;
  return CLAUDE_DOC.test(path) || LANE_PROMPT.test(path) || TEMPLATE.test(path) || DOC.test(path);
}

/** The instruction files in a path list: filtered, de-duplicated, sorted. */
export function instructionFiles(paths) {
  return [...new Set(paths.filter(isInstructionFile))].sort();
}

/** Why a path must never be hand-edited (generated, verbatim or append-only), or null. */
export function doNotEditReason(path) {
  return DO_NOT_EDIT.find((rule) => rule.test.test(path))?.why ?? null;
}
