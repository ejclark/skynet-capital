/**
 * Follow-up on a filed feedback issue — a member adding more detail after the fact ("actually,
 * here's a screenshot" / "still happening", or correcting something they got wrong) needed a way
 * back into the loop that doesn't require them to leave the app or have a GitHub account.
 *
 * Deliberately a COMMENT, never an edit to the original issue body: the body carries structured
 * content the build lane parses (the `skynet-spec` block, the labels, the attribution footer —
 * feedback-issue.ts) and a member-editable PATCH risks corrupting that. A comment is the native
 * GitHub way to add or correct information on a thread without disturbing the original post, and
 * it keeps the audit trail (what was said, when) instead of overwriting it.
 *
 * On a filing that is `ready` and not yet claimed, the follow-up ALSO takes `ready` off, BEFORE
 * the comment posts, and never puts it back itself (#7548). The filing check re-judges the filing
 * with the follow-up in it (`assessIntent` in scripts/moneypenny/triage-assess.mjs, told by the
 * trailer's last sentence, `RECHECK_MARK`) and re-applies `ready` only if it is still clear. Until
 * then this file cycled `ready` to restart the build (#5848), and the build read the follow-up
 * unchecked, so once a small clear ask readied itself in minutes (#7546) a follow-up could carry a
 * large one past every check. Off before the comment, not after: the comment event's payload must
 * show no `ready` to the filing check, and the claim's retry sweep must not take the filing in
 * between. Taking a label off is an `unlabeled` event, which never opens claude.yml's lane
 * (it listens to `opened` and `labeled`). A filing still in Backlog gets the comment and nothing
 * else, and so does one a build already holds (`in-progress` — the running build reads it) or one
 * parked on a person; the result names which, so the screen never promises what won't happen.
 *
 * WHO GITHUB SAYS WROTE IT (corrected 2026-11-10, #7286 slice 8 review). This route's token
 * comments under the owner's login, so GitHub reports every relayed follow-up with author
 * association OWNER — the same as a comment Eric typed (seen on #1043: comment 5473411390 started a
 * claude.yml run). Three lanes act on an OWNER comment, and each is closed to a relayed one here,
 * not in the prompt:
 *  - `claude.yml` starts an unrestricted session on any OWNER comment that does not carry the link
 *    opener `[Claude Code](https://claude` (its gate's exclusion for its own comments). The relay
 *    trailer (`relayTrailer`) carries that link, so the gate skips it; the spec reads the gate's
 *    exclusion out of the workflow file, so a change there fails it. The same gate fires on an
 *    `issues` event whose BODY mentions the lane without that link — and adding `ready` under the
 *    owner's token is one (#7444). Filings carry the link in their footer since then
 *    (feedback-issue.ts); this file adds `ready` only to undo a hold whose comment failed, and
 *    never on an older body that still opens the gate (`opensClaudeLane`).
 *  - the plan lane reads an owner comment as a go: any issue carrying `plan` is refused before the
 *    comment posts (`readBeforePosting`).
 *  - the reply-resume step reads an owner comment as the answer to a parked question: a filing
 *    parked `needs-eric` is refused before the comment posts, and `replyResumeIntent` refuses a
 *    relayed reply that would answer `needs-eric` or add `ready` to a filing never readied
 *    (`isRelayedFollowup` in scripts/moneypenny/reply-resume.mjs). A relayed answer to the build
 *    lane's own `needs-info` question on a `ready` filing still resumes it — that is its job, and
 *    such a filing is parked, so this file never holds it.
 * The trailer's link text carries no "Generated by", so the lanes' own footer check
 * (`isClaudeComment`) still reads it as a person's reply.
 */
import {
  notPullableReason,
  PARKING_LABELS,
  type PullableIssue,
} from "../../scripts/moneypenny/labels.mjs";
import { hasPlanLabel } from "../../scripts/moneypenny/plan-claim.mjs";
import { RECHECK_MARK, RELAY_TRAILER_OPENER } from "../../scripts/moneypenny/reply-resume.mjs";
import { fetchJson, type JsonResponse } from "../http/fetch-json.js";
import { CLAUDE_CODE_LINK, submitterFor } from "./feedback-attribution.js";
import { githubErrorMessage, githubHeaders } from "./github-api.js";

type DoFetch = typeof fetchJson;

interface FeedbackFollowupInput {
  readonly issueNumber: number;
  readonly body: string;
  readonly submitterEmail?: string;
  readonly submitterName?: string;
}

/** What the follow-up did to the build, so the screen can say it honestly (#5848, #7548):
 *  - `rechecking` — the filing was `ready` and unclaimed: `ready` came off, and the filing check
 *    puts it back only if the filing, follow-up included, is still clear;
 *  - `backlog` — open but not `ready`: the comment waits with it for the queue;
 *  - `held` — parked on a person (a parking label): it waits on them first;
 *  - `building` — already `in-progress`: a build is running now and reads it;
 *  - `closed` — the issue is closed (shipped or not built): nothing picks it up again;
 *  - `unchanged` — anything else the pull rule named: no promise either way. */
export type FollowupOutcome =
  | "rechecking"
  | "backlog"
  | "held"
  | "building"
  | "closed"
  | "unchanged";

type FollowupResult =
  | {
      readonly ok: true;
      readonly url: string;
      readonly outcome: FollowupOutcome;
    }
  | { readonly ok: false; readonly error: string };

export type SubmitFollowup = (input: FeedbackFollowupInput) => Promise<FollowupResult>;

interface FollowupConfig {
  readonly token: string;
  readonly repo: string;
}

/** Where an operator-facing line goes — the server log at boot (src/scripts/dashboard-feedback.ts),
 *  silent by default so specs stay quiet. */
type Warn = (line: string) => void;

const ok2xx = (res: JsonResponse): boolean => res.status >= 200 && res.status < 300;

type LabelledIssue = PullableIssue & {
  readonly labels: readonly unknown[];
  readonly body?: unknown;
};

const names = (issue: LabelledIssue): readonly string[] =>
  issue.labels
    .map((l) => (l as { name?: unknown } | null)?.name)
    .filter((n) => typeof n === "string");

/** Which rule the pull rule refused on, read off `notPullableReason`'s first failing rule, for a
 *  filing this follow-up does not hold. A wording change there lands on `unchanged` (no promise),
 *  and the spec walks the real rule for each case, so it fails until this list catches up. */
const REFUSED: readonly (readonly [RegExp, FollowupOutcome])[] = [
  [/ is not open$/, "closed"],
  [/does not carry `ready`/, "backlog"],
  [/ is parked by /, "held"],
  [/already `in-progress`/, "building"],
];
const refusedAs = (reason: string): FollowupOutcome =>
  REFUSED.find(([rule]) => rule.test(reason))?.[1] ?? "unchanged";

/**
 * Hold this filing out of the build for the filing check? Pure. Yes when it is open, `ready`, not
 * yet claimed (`in-progress`) and parked on nobody — the EARS rows of #7548. A blocked or
 * `needs-session` filing is held too: the claim refuses it today but takes it later, and would read
 * the follow-up then. A parked one is not: `ready` + a parking label means the build lane asked a
 * question, and a relayed answer to it resumes that build (reply-resume.mjs) — its own question,
 * its own reader.
 */
export function holdsForRecheck(issue: LabelledIssue): boolean {
  if (issue.state !== "open") return false;
  const on = names(issue);
  return (
    on.includes("ready") &&
    !on.includes("in-progress") &&
    !on.some((n) => PARKING_LABELS.includes(n))
  );
}

/** Would `claude.yml`'s gate start a session on an `issues` event for this body? It does when the
 *  body mentions the lane and lacks the excluded link — GitHub's `contains` ignores case. Filings
 *  made before #7444 carry no link in their footer, so a member's own mention opens it there. A
 *  null or missing body mentions nothing. tests/server/feedback-followup-gate.spec.ts reads both
 *  strings out of the workflow, so a change to the gate fails it. Asked only before putting `ready`
 *  BACK (a `labeled` event under the owner's token); taking it off opens nothing. */
const LANE_MENTION = "@claude";
function opensClaudeLane(body: unknown): boolean {
  if (typeof body !== "string") return false;
  const text = body.toLowerCase();
  return text.includes(LANE_MENTION) && !text.includes(CLAUDE_CODE_LINK.toLowerCase());
}

/** A label write that may throw (network) reads as a failed one. */
async function write(attempt: () => Promise<JsonResponse>): Promise<boolean> {
  try {
    return ok2xx(await attempt());
  } catch {
    return false;
  }
}

const CANT_CHECK =
  "Couldn't check that filing just now, so nothing was posted. Try again in a minute.";
const ON_A_PLAN =
  "That filing has become a plan, and follow-ups aren't taken on plans here, so nothing was posted.";
const WAITS_ON_ERIC =
  "That filing is waiting on a decision from Eric, so follow-ups are paused on it until he answers, and nothing was posted.";

/** The line under every relayed follow-up: who it is from, and the link opener `claude.yml`'s gate
 *  excludes, so a member's words never start an unrestricted session (header). A held follow-up
 *  ends with `RECHECK_MARK`, the filing check's cue to re-judge it (#7548). */
export const relayTrailer = (who: string, held = false): string =>
  `---\n${RELAY_TRAILER_OPENER}${who}, relayed by the app: a member's words, not a ${CLAUDE_CODE_LINK} instruction.${held ? ` ${RECHECK_MARK}` : ""}_`;

/**
 * READ BEFORE POSTING, AND FAIL CLOSED (#7286 slice 8, #7548). One GET for the issue as it stands
 * (never anything the app cached). This route's token comments as the owner's login, and the plan
 * lane reads an owner's comment as a go (`isReadySignal` in scripts/moneypenny/plan-claim.mjs) — so
 * a member's "ready", relayed onto a filing that has since become a plan, would read as the owner's
 * authorization: any issue carrying `plan` is refused, and so is one parked `needs-eric`, whose
 * reply-resume step would read the relayed comment as Eric's answer (header). The same read decides
 * the hold. A read that fails, or answers no label list, posts nothing: a comment that can't be
 * checked is the one that could reach a plan or a build unchecked. Ownership is the caller's check
 * (`serveFollowup`, against the member's own feedback log); this guard sits here so every door that
 * follows up — the Feedback screen and Moneypenny's card — goes through it.
 */
async function readBeforePosting(
  issueUrl: string,
  config: FollowupConfig,
  doFetch: DoFetch,
): Promise<{ readonly issue: LabelledIssue } | { readonly refused: string }> {
  let res: JsonResponse;
  try {
    res = await doFetch("GET", issueUrl, githubHeaders(config.token));
  } catch {
    return { refused: CANT_CHECK };
  }
  const issue = ok2xx(res) ? (res.body as LabelledIssue | undefined) : undefined;
  if (!issue || typeof issue !== "object" || !Array.isArray(issue.labels)) {
    return { refused: CANT_CHECK };
  }
  if (hasPlanLabel({ labels: issue.labels })) return { refused: ON_A_PLAN };
  // A relayed comment reads as the owner's, so it must never land as the answer to Eric's decision.
  if (names(issue).includes("needs-eric")) return { refused: WAITS_ON_ERIC };
  return { issue };
}

/** The comment did not post on a held filing: put `ready` back (one retry), unless re-labelling
 *  would open claude.yml's lane on an older filing's body. Either miss is logged for an operator. */
async function restoreReady(
  issueNumber: number,
  issue: LabelledIssue,
  issueUrl: string,
  config: FollowupConfig,
  doFetch: DoFetch,
  warn: Warn,
): Promise<void> {
  const readd = () =>
    doFetch("POST", `${issueUrl}/labels`, githubHeaders(config.token), {
      labels: ["ready"],
    });
  if (!opensClaudeLane(issue.body) && ((await write(readd)) || (await write(readd)))) return;
  warn(
    `[feedback-followup] #${issueNumber} lost \`ready\` — taken off for a follow-up that then ` +
      "failed to post, and not put back; re-add `ready` by hand so the filing returns to the Ready column",
  );
}

/** Build the bound follow-up function. Live path (uses global fetch); `doFetch` is injectable so
 *  tests never hit the network, same discipline as `uploadFeedbackImages` / `createStatusFetcher`. */
export function createFollowup(
  config: FollowupConfig,
  doFetch: DoFetch = fetchJson,
  warn: Warn = () => undefined,
): SubmitFollowup {
  return async (input) => {
    const body = input.body.trim();
    if (!body)
      return {
        ok: false,
        error: "Add a few words so there's something to follow up on.",
      };
    const issueUrl = `https://api.github.com/repos/${config.repo}/issues/${input.issueNumber}`;
    const read = await readBeforePosting(issueUrl, config, doFetch);
    if ("refused" in read) return { ok: false, error: read.refused };
    const { issue } = read;

    const held = holdsForRecheck(issue);
    // Off before the comment posts, or the follow-up could land on a filing a build then claims
    // unchecked — so a hold that fails posts nothing.
    if (
      held &&
      !(await write(() =>
        doFetch("DELETE", `${issueUrl}/labels/ready`, githubHeaders(config.token)),
      ))
    ) {
      return { ok: false, error: CANT_CHECK };
    }

    const commentBody = `${body}\n\n${relayTrailer(submitterFor(input), held)}`;
    let res: JsonResponse;
    try {
      res = await doFetch("POST", `${issueUrl}/comments`, githubHeaders(config.token), {
        body: commentBody,
      });
    } catch (error) {
      if (held) await restoreReady(input.issueNumber, issue, issueUrl, config, doFetch, warn);
      return {
        ok: false,
        error: error instanceof Error ? error.message : "Couldn't reach GitHub.",
      };
    }
    if (res.status !== 201) {
      if (held) await restoreReady(input.issueNumber, issue, issueUrl, config, doFetch, warn);
      return { ok: false, error: githubErrorMessage(res) };
    }

    const refused = held ? null : notPullableReason({ ...issue, number: input.issueNumber });
    return {
      ok: true,
      url: `https://github.com/${config.repo}/issues/${input.issueNumber}`,
      outcome: held ? "rechecking" : refused === null ? "unchanged" : refusedAs(refused),
    };
  };
}

/** Env factory — `undefined` (inert) until `SKYNET_FEEDBACK_GITHUB_TOKEN` is set, mirroring
 *  `resolveFeedback` in feedback-service.ts (same token, same repo default). */
export function resolveFeedbackFollowup(
  env: Readonly<Record<string, string | undefined>>,
  warn?: Warn,
): SubmitFollowup | undefined {
  const token = env.SKYNET_FEEDBACK_GITHUB_TOKEN;
  if (!token) return undefined;
  const repo = env.SKYNET_FEEDBACK_REPO ?? "ejclark/skynet-capital";
  return createFollowup({ token, repo }, fetchJson, warn);
}
